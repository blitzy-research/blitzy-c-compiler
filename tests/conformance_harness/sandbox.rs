// The well-known entries of a cell workspace. Named here so that the module which compiles a
// cell, the module which runs it and the module which writes its finding artifacts all refer
// to one spelling: a divergence between two hard-coded strings would surface as an absent
// artifact rather than as an error.

/// The copy of the program source that makes a workspace self-contained.
///
/// A retained workspace is reproducible on its own because the program travels with the
/// artifacts and the command lines, so investigating a divergence never depends on the corpus
/// still holding exactly the bytes that produced it.
pub const PROGRAM_SOURCE_NAME: &str = "program.c";

/// The copy of the program's expectation record that makes a workspace self-contained.
///
/// The record is what states the targets, the optimization levels, the command templates, the
/// expected termination and the golden standard output, so a retained workspace holding the program
/// without it is only half a reproducer: a maintainer could rebuild the artifacts but not know what
/// the cell was asserting. Copying both is what makes "source file, build commands, and expected
/// output recorded together" true of the retained directory itself and not merely of the corpus it
/// came from.
///
/// Copied in beside the program at allocation, under a fixed name sharing the stem of
/// [`PROGRAM_SOURCE_NAME`] rather than the corpus stem, so every workspace holds its two inputs in
/// the same two places and as the sibling pair of one stem the suite requires everywhere else.
pub const PROGRAM_RECORD_NAME: &str = "program.expected";

