//! Per-cell workspace management for the differential conformance suite.
//!
//! Every compile-and-run cell of the build matrix gets one directory of its own. This
//! module is the only thing in the suite that decides where that directory is, creates it,
//! writes into it and removes it, which is what lets the suite's whole artifact-and-path
//! discipline be checked by reading one file.
//!
//! # What the discipline is, and what it is not
//!
//! The guarantee this module provides is **path discipline over harness-managed writes**: the
//! paths this suite constructs are derived from a cell's identity, validated, and confined to
//! the three roots below, and the corpus is opened read-only. That is a property of the code
//! and is checkable here.
//!
//! It is **not an operating-system sandbox**, and reading it as one would be a mistake worth
//! naming explicitly. Nothing here isolates syscalls or the network, enters a namespace or a
//! `chroot`, or restricts what an absolute path handed to an external tool may reach. Three
//! consequences follow directly and are stated rather than left to be discovered:
//!
//! - **A tool that hard-codes a temporary path keeps its own temporaries there.** The suite does
//!   clear every child's environment and point `TMPDIR`, `TMP`, `TEMP` and `HOME` at the cell's
//!   workspace — that happens at the spawn sites, not here — but a reference compiler driver that
//!   writes intermediate files under the system temporary directory without consulting those
//!   variables is unaffected: `gcc -###` shows `/tmp/cc*` entries for the assembler input, the
//!   object and the linker response file, and this module neither sees nor relocates them.
//! - **The bounding utility and the execution runners live outside the build tree.** The
//!   system `timeout` utility and the QEMU runners are executed from wherever they are
//!   installed; only the artifact they are pointed at is required to be inside a workspace.
//! - **A crash dump is the host's decision.** Whether a signalled child writes a core image,
//!   and where it lands, is decided by the host's `kernel.core_pattern` and core-size limit.
//!
//! What keeps the *programs under test* from reaching the network or the wider filesystem is
//! therefore corpus-authoring policy rather than enforcement here: every corpus program takes
//! its whole input from literals in its own source, opens no socket and no file. That policy is
//! auditable because the corpus is committed, and it is the half of constraint four this suite
//! actually discharges.
//!
//! # The three write roots, and nothing else
//!
//! The suite writes beneath exactly three directories, all of them inside the Cargo build
//! directory: [`work_root`] (one workspace per cell), [`report_root`] (one file per feature
//! area plus the run summary) and [`findings_root`] (findings generated by the current run).
//! This module owns the first and, in [`ensure_roots`], creates all three, establishes the run's
//! identity once per process, and retires the previous run's account of itself.
//!
//! Two things follow, and both are properties of the code rather than promises about it:
//!
//! - **The corpus is read-only to the harness.** A program's `.c` file and its sibling
//!   `.expected` record are read and *copied into* a workspace by [`Workspace::copy_in`];
//!   they are never modified in place. No function here returns a writable handle to
//!   anything under the corpus, so the committed, curated finding set that ships as a
//!   deliverable cannot be polluted by a run in progress.
//! - **This module opens no socket.** The only operations it performs are local filesystem
//!   calls from [`std::fs`]. It does not follow that a child process it later hands a path to
//!   is similarly constrained; that is the distinction the section above draws.
//!
//! # Layout
//!
//! ```text
//! target/conformance-report/run.txt          which run produced the reports beside it
//! target/conformance-work/                                  <- work_root()
//! |
//! +-- 01_integer_conversions+004_narrowing_conversions+x86_64+O0/
//! |   +-- program.c        a copy of the corpus program, so the directory stands alone
//! |   +-- program.expected a copy of its expectation record, so the directory also states
//! |   |                    what the result was supposed to be
//! |   +-- bcc.out          artifact built by the compiler under test
//! |   +-- ref.out          artifact built by the reference compiler
//! |   +-- bcc.stdout   bcc.stderr   bcc.exit
//! |   +-- ref.stdout   ref.stderr   ref.exit
//! |   +-- commands.txt     the exact rendered command lines for this cell
//! |
//! +-- _flagprobe/<flag>/                     one directory per flag the probe verifies
//! +-- _ubaudit/<area>/<program>/<gate>/      one directory per audit gate invocation
//! ```
//!
//! The well-known entry names above are spelled once, as the `*_NAME` constants below, so
//! the modules that build a cell, run it and write its finding artifacts cannot disagree
//! about which file is which.
//!
//! ## Why one flat directory per cell rather than a nested tree
//!
//! A cell's directory name is [`CellKey::slug`], which already encodes all four components
//! of the cell's identity — feature area, program, target and optimization level — as a
//! single path component, so the directory is one level beneath the work root rather than
//! four.
//!
//! That is not a stylistic choice. [`Cell::new`] derives a cell's own workspace with the same
//! expression and then *rejects* any derivation that is not a direct child of the work root,
//! because the derived workspace is the one directory a cell may write into. Were this module
//! to nest instead, the same cell would have two different directory names: the compile step
//! would place `bcc.out` in the path carried by its [`Cell`], while the execute step would run
//! with a working directory somewhere else entirely, and the artifacts would silently fail to
//! line up. [`for_resolved_cell`] exists to make that impossible — it checks the derivation in
//! this module against the one already carried by a resolved [`Cell`] and fails loudly if they
//! ever diverge.
//!
//! ## Determinism, and why it is preferred to unpredictability here
//!
//! A workspace path is a pure function of the cell's identity. It contains no clock reading,
//! no counter, no process or thread identifier and no unpredictable element of any kind, so
//! the same cell yields the same path in every process and on every run.
//!
//! The conventional instinct would be a scratch directory with an unpredictable name. It is
//! the wrong tool for this suite: the artifact being chased is a compiler divergence across
//! more than a thousand cells, and a maintainer reading one row of a report must be able to
//! predict, from that row alone, exactly which directory to open. Reproducibility is worth
//! more here than unpredictability, so it is what the naming optimizes for.
//!
//! Determinism also supplies the parallel-safety argument. [`CellKey::slug`] is injective,
//! so two distinct cells cannot name the same directory, and the feature-area tests can run
//! concurrently — as `cargo test` does by default — with no lock and no coordination over any
//! *path*.
//!
//! The module does hold shared mutable state, and only for one purpose: the run's retention
//! accounting. A ceiling on what a whole run may keep is by definition a fact about the run
//! rather than about any one cell, so it cannot be derived from a cell's identity the way a path
//! can. It is therefore kept in two atomics and one mutex-guarded list of notes, all of them
//! write-mostly and none of them consulted to decide *where* anything is written — so the
//! hermeticity argument above still rests on pure functions of the cell identity, and the
//! concurrency argument for paths is unchanged.
//!
//! ## Stale artifacts, and why allocation purges
//!
//! Because paths are deterministic, a second run finds the directory the previous run left
//! behind. Allocation therefore removes the directory tree and recreates it, so a workspace
//! is always empty when its cell begins. Skipping that step would be a correctness bug rather
//! than untidiness: a leftover `bcc.out` from an earlier build compared against a freshly
//! produced `ref.out` would yield a verdict about two different compilations and report it as
//! though it meant something.
//!
//! The same reasoning applies one level up, to the run's *account of itself*, and that is why
//! [`ensure_roots`] does more than create directories. A per-area report and a generated finding
//! also live at deterministic paths, so a previous run's `areas/09_optimization_levels.tsv` sits
//! exactly where this run's will and a previous run's finding directory sits exactly where this
//! run's would. Finalization would then aggregate a set of files that never described one run — a
//! reduced run's rows counted beside a full run's, or a finding fixed weeks ago presented as
//! current — and the summary would state that total with no way for a reader to tell. Both are
//! therefore retired once, at the start of the run, and the run's identity is written to
//! [`RUN_MANIFEST_NAME`] beside the reports so a reader can see whose they are.
//!
//! ## Retention policy
//!
//! The success and failure paths are both explicit at the call site, and both consume the
//! workspace:
//!
//! - [`Workspace::discard`] removes the directory once its cell has passed. It removes
//!   nothing when the run was asked to keep every workspace.
//! - [`Workspace::retain`] leaves the directory in place, so a cell that failed — including a
//!   cell that timed out, which is a divergence like any other — leaves behind exactly the
//!   artifacts needed to investigate it, and returns a [`Retention`] naming the path so a report
//!   can send a maintainer to it.
//!
//! A retained directory is complete in a specific, checkable sense: it holds the program
//! ([`PROGRAM_SOURCE_NAME`]) and its expectation record ([`PROGRAM_RECORD_NAME`]) as copies,
//! both compiled artifacts, every captured stream, the recorded termination statuses, and the
//! exact rendered command lines ([`COMMANDS_NAME`]) — and those command lines name the copied
//! source rather than the corpus one, so the recipe in the directory rebuilds the bytes in the
//! directory. Nothing in it refers to a file that a later corpus edit could change underneath it.
//!
//! Deliberately, this type has no destructor that deletes. A destructor would run while a
//! panicking cell unwound and would erase the evidence for precisely the cell whose evidence
//! matters most.
//!
//! ### Retention is bounded, and every bound is reported
//!
//! Retention is the one thing here that would otherwise grow without limit: 1,296 cells, each
//! keeping its directory when it does not pass, and the run in which the compiler under test
//! builds nothing at all is the run in which all of them do. Ceilings therefore apply at the moment
//! of retention — an entry whose size could not be established at all, then one entry, then one
//! workspace, then the run as a whole — and pruning removes the largest entries first, so the
//! executables go and the captured streams, recorded statuses and command lines stay. Every pruning
//! is recorded in the returned [`Retention`] and in [`retention_pruning_notes`], because a pruned
//! workspace and a workspace that never existed look identical on disk and mean opposite things.
//!
//! Each ceiling is compared against a figure that was **proved**: measurement is bounded rather than
//! recursive, bytes are discharged only by a deletion that was confirmed, and the charge finally made
//! against the run's budget is a fresh measurement of the directory rather than arithmetic over what
//! was listed a moment earlier. Where a ceiling still cannot be enforced, the run says so and stops
//! scheduling cells, because a budget that has silently stopped holding is worse than no budget: the
//! report stays confident while the build volume fills.
//!
//! Edition 2021, minimum supported Rust 1.70. Only the standard library is used, as the
//! project permits no third-party crate; this module is what stands in for a scratch-directory
//! crate.

