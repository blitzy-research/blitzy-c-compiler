/// One of the four target architectures bcc supports.
///
/// The triple spellings, widths and ELF classes below come from the repository's own
/// target table rather than from this suite.
///
/// # Implementation-defined properties this harness does not branch on
///
/// Plain `char` signedness, `sizeof(long)` and `sizeof(void *)`, and `sizeof(long double)` all
/// differ across these targets. A divergence caused by an implementation-defined difference is
/// not a compiler defect, so each is handled by how a program is written or by a per-oracle
/// exclusion in that program's expectation record — never by harness logic. The two widths are
/// exposed by [`Target::long_width_bytes`] and [`Target::pointer_width_bytes`] for report
/// legends and fingerprints, not for branching.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Target {
    /// x86-64, and the baseline for oracle (b).
    X86_64,
    /// i686, the only ELF32 target.
    I686,
    Aarch64,
    Riscv64,
}

impl Target {
    /// Every target, in the repository's documented table order. [`Target::parse`]
    /// searches this array, so the accepted and emitted spellings are the same set.
    pub const ALL: [Target; 4] = [
        Target::X86_64,
        Target::I686,
        Target::Aarch64,
        Target::Riscv64,
    ];

    /// The baseline every other target is compared against under oracle (b).
    ///
    /// x86-64 is chosen because it is the intended host architecture, so a baseline cell
    /// runs without an emulator and introduces no emulation-related variable.
    pub const BASELINE: Target = Target::X86_64;

    /// The canonical target triple, spelled as the repository's target table spells it and
    /// as bcc's target-selection flag expects it.
    pub fn triple(self) -> &'static str {
        match self {
            Target::X86_64 => "x86_64-linux-gnu",
            Target::I686 => "i686-linux-gnu",
            Target::Aarch64 => "aarch64-linux-gnu",
            Target::Riscv64 => "riscv64-linux-gnu",
        }
    }

    /// The short slug used in workspace paths, report rows and artifact filenames.
    ///
    /// Not the name of the target's emulator: the i686 runner is spelled `qemu-i386`, so
    /// runner names live in `env.rs` and this module exposes only the slug.
    pub fn short_name(self) -> &'static str {
        match self {
            Target::X86_64 => "x86_64",
            Target::I686 => "i686",
            Target::Aarch64 => "aarch64",
            Target::Riscv64 => "riscv64",
        }
    }

    /// ELF class of this target's output: 32 for i686, 64 for the other three.
    ///
    /// `flagprobe.rs` needs it to pick the right header layout when it reads an ELF
    /// identification field directly, which is how `-c`, `-static` and `-g` are verified
    /// without depending on a binary-inspection tool being installed.
    pub fn elf_class(self) -> u8 {
        match self {
            Target::I686 => 32,
            Target::X86_64 | Target::Aarch64 | Target::Riscv64 => 64,
        }
    }

    /// Pointer width in bytes: four on i686, eight on the other three.
    ///
    /// Consumed by report legends and by the environment fingerprint written into every
    /// finding, so a width-related divergence can be read off the artifact directly.
    pub fn pointer_width_bytes(self) -> u8 {
        match self {
            Target::I686 => 4,
            Target::X86_64 | Target::Aarch64 | Target::Riscv64 => 8,
        }
    }

    /// Width of `long` in bytes: four on i686, eight on the other three.
    ///
    /// Same consumers as [`Target::pointer_width_bytes`]. Corpus programs normalize the
    /// difference away rather than relying on it.
    pub fn long_width_bytes(self) -> u8 {
        match self {
            Target::I686 => 4,
            Target::X86_64 | Target::Aarch64 | Target::Riscv64 => 8,
        }
    }

    /// True when this target's binaries execute directly on the host, with no emulator.
    ///
    /// The host architecture is read at run time rather than assumed. The i686 arm is
    /// matched against `x86`, which is how the standard library spells 32-bit x86.
    ///
    /// i686 is therefore reported as non-native on an x86-64 host even though such a host
    /// can usually execute 32-bit binaries. That is deliberate: routing i686 through its
    /// emulator like AArch64 and RISC-V 64 keeps the emulation variable uniform across
    /// all three non-baseline targets and leaves the baseline as the only emulator-free
    /// arm.
    pub fn is_native(self) -> bool {
        let host = std::env::consts::ARCH;
        match self {
            Target::X86_64 => host == "x86_64",
            Target::I686 => host == "x86",
            Target::Aarch64 => host == "aarch64",
            Target::Riscv64 => host == "riscv64",
        }
    }

    /// Parse a target from either its full triple or its short slug, ignoring surrounding
    /// whitespace.
    ///
    /// Both spellings are accepted because expectation records list targets in the short
    /// form (`targets = x86_64, i686, aarch64, riscv64`) while command templates and
    /// report rows use the triple. Returns `None` for anything else, which the caller must
    /// report as a defect in the expectation record rather than drop the cell.
    pub fn parse(text: &str) -> Option<Target> {
        let wanted = text.trim();
        Target::ALL
            .iter()
            .copied()
            .find(|candidate| candidate.triple() == wanted || candidate.short_name() == wanted)
    }
}

impl fmt::Display for Target {
    /// `{}` renders the canonical triple; `{:#}` renders the fact row report legends and
    /// finding fingerprints need — triple, pointer width, `long` width, ELF class, byte
    /// order, execution mode and baseline role.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if !f.alternate() {
            return f.write_str(self.triple());
        }
        let execution = if self.is_native() {
            "native execution"
        } else {
            "emulated execution"
        };
        let role = if *self == Target::BASELINE {
            "oracle_b baseline"
        } else {
            "compared against the oracle_b baseline"
        };
        write!(
            f,
            "{} (pointer {} bytes, long {} bytes, ELF{}, little-endian, {}, {})",
            self.triple(),
            self.pointer_width_bytes(),
            self.long_width_bytes(),
            self.elf_class(),
            execution,
            role,
        )
    }
}

impl std::str::FromStr for Target {
    type Err = HarnessError;

    /// [`Target::parse`] for callers that want an explanatory error instead of `None`.
    fn from_str(text: &str) -> Result<Target, HarnessError> {
        Target::parse(text).ok_or_else(|| {
            HarnessError::new(
                "parsing a target architecture",
                format!(
                    "{text:?} is not one of the four supported targets; expected a triple or short \
                     name from: {}",
                    joined_target_names()
                ),
            )
        })
    }
}

/// Every accepted target spelling, as one comma-separated line for diagnostics.
fn joined_target_names() -> String {
    let mut rendered = String::new();
    for target in Target::ALL {
        if !rendered.is_empty() {
            rendered.push_str(", ");
        }
        rendered.push_str(target.short_name());
        rendered.push_str(" / ");
        rendered.push_str(target.triple());
    }
    rendered
}

/// Render a list of static labels as one comma-separated line for diagnostics.
fn comma_separated(labels: &[&str]) -> String {
    labels.join(", ")
}

/// An optimization level in the sweep.
///
/// These three levels are the whole sweep: levels above `-O2` and size-directed levels are
/// documented as out of scope, so no variant for them exists — not even an unused one,
/// which would invite a maintainer to start passing one. Comparing output across the
/// levels is what makes the suite a semantic-preservation test rather than a check that a
/// particular optimization occurred.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum OptLevel {
    O0,
    O1,
    /// The highest level in scope.
    O2,
}

impl OptLevel {
    /// Every optimization level, in ascending order. [`OptLevel::parse`] searches it.
    pub const ALL: [OptLevel; 3] = [OptLevel::O0, OptLevel::O1, OptLevel::O2];

    /// The command-line spelling, passed identically to bcc and to the reference compiler.
    pub fn flag(self) -> &'static str {
        match self {
            OptLevel::O0 => "-O0",
            OptLevel::O1 => "-O1",
            OptLevel::O2 => "-O2",
        }
    }

    /// The bare spelling used in workspace paths, report rows and artifact filenames,
    /// where a leading dash would be awkward.
    pub fn short(self) -> &'static str {
        match self {
            OptLevel::O0 => "O0",
            OptLevel::O1 => "O1",
            OptLevel::O2 => "O2",
        }
    }

    /// Parse an optimization level from either spelling, ignoring surrounding whitespace.
    ///
    /// Both are accepted because expectation records list the levels in flag form
    /// (`opt_levels = -O0, -O1, -O2`) while report rows and artifact names use the bare
    /// form.
    pub fn parse(text: &str) -> Option<OptLevel> {
        let wanted = text.trim();
        OptLevel::ALL
            .iter()
            .copied()
            .find(|candidate| candidate.flag() == wanted || candidate.short() == wanted)
    }
}

impl fmt::Display for OptLevel {
    /// Renders the command-line spelling, so a rendered level can be pasted straight into
    /// a reproduction command.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.flag())
    }
}

impl std::str::FromStr for OptLevel {
    type Err = HarnessError;

    fn from_str(text: &str) -> Result<OptLevel, HarnessError> {
        OptLevel::parse(text).ok_or_else(|| {
            HarnessError::new(
                "parsing an optimization level",
                format!(
                    "{text:?} is not an optimization level in scope; expected one of: {}",
                    comma_separated(&OptLevel::ALL.map(OptLevel::flag))
                ),
            )
        })
    }
}

/// Which of the three independent oracles produced a comparison.
///
/// Oracle identity is a value rather than a property of a call site so that an exclusion
/// can be expressed per oracle: a construct whose value legitimately differs between
/// architectures stays fully compared against its same-target reference while being
/// excluded from cross-backend value equality alone.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Oracle {
    /// bcc versus an external reference C compiler, same target and optimization level.
    ReferenceCompiler,
    /// Every non-baseline target versus [`Target::BASELINE`] at the same optimization
    /// level, which is where ABI, register-allocation and instruction-selection
    /// differences surface.
    CrossBackend,
    /// Every cell versus the `expected_stdout` recorded in the program's own expectation
    /// record, which is the only oracle that detects both compilers changing behaviour in
    /// the same direction at once.
    GoldenRecord,
}

impl Oracle {
    /// Every oracle, in requirement order. [`Oracle::parse`] searches it.
    pub const ALL: [Oracle; 3] = [
        Oracle::ReferenceCompiler,
        Oracle::CrossBackend,
        Oracle::GoldenRecord,
    ];

    /// The single letter that names this oracle in the requirements. `findings.rs` builds
    /// artifact filenames of the form `outputs/<letter>-<target>-<opt>.stdout` from it.
    pub fn letter(self) -> char {
        match self {
            Oracle::ReferenceCompiler => 'a',
            Oracle::CrossBackend => 'b',
            Oracle::GoldenRecord => 'c',
        }
    }

    /// The human-readable label used in reports and failure messages. Its leading token
    /// matches the per-oracle toggle key in an expectation record, so a report line and
    /// the record that governs it name the oracle the same way.
    pub fn label(self) -> &'static str {
        match self {
            Oracle::ReferenceCompiler => "oracle_a (reference compiler)",
            Oracle::CrossBackend => "oracle_b (cross-backend)",
            Oracle::GoldenRecord => "oracle_c (golden record)",
        }
    }

    /// Parse an oracle from its letter (`a`), its record key (`oracle_a`) or its full
    /// label, ignoring surrounding whitespace. All three forms are accepted because
    /// records use the key, reports use the label, and artifact names use the letter.
    pub fn parse(text: &str) -> Option<Oracle> {
        let wanted = text.trim();
        let bare = wanted.strip_prefix("oracle_").unwrap_or(wanted);
        Oracle::ALL.iter().copied().find(|candidate| {
            if wanted == candidate.label() {
                return true;
            }
            let mut characters = bare.chars();
            characters.next() == Some(candidate.letter()) && characters.next().is_none()
        })
    }
}

impl fmt::Display for Oracle {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.label())
    }
}

impl std::str::FromStr for Oracle {
    type Err = HarnessError;

    fn from_str(text: &str) -> Result<Oracle, HarnessError> {
        Oracle::parse(text).ok_or_else(|| {
            HarnessError::new(
                "parsing an oracle identity",
                format!(
                    "{text:?} names no oracle; expected a letter, a record key or a label from: {}",
                    comma_separated(&Oracle::ALL.map(Oracle::label))
                ),
            )
        })
    }
}

/// The shape a divergence took, independently of how it was classified into a verdict.
///
/// The set is closed at six members and stays closed: a newly observed failure shape is
/// mapped onto one of these rather than appended as a seventh, so the classification table
/// in `classify.rs` remains total. The labels are the tokens an expectation record uses in
/// the `class` field of an expected-divergence marker.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum DivergenceClass {
    /// One compiler rejected a program the other accepted. The diagnostics are captured
    /// even though they are never compared.
    CompileFailure,
    /// Compilation succeeded but the artifact failed to link — most often because a
    /// target's C runtime is missing, which the environment fingerprint in a finding is
    /// what distinguishes from a compiler defect.
    LinkFailure,
    /// The program terminated on a signal instead of exiting normally. Exit status is
    /// compared as a raw wait status so this is never conflated with a numerically equal
    /// ordinary exit.
    RunCrash,
    ExitCodeMismatch,
    /// The compared stdout byte streams differ. The first divergent line and byte offset
    /// are reported, because a divergence that cannot be located cannot be minimized.
    StdoutMismatch,
    /// Execution exceeded its per-cell budget. A divergence class rather than an
    /// infrastructure error, since a program that finishes promptly under one compiler and
    /// hangs under another is a defect worth surfacing.
    Timeout,
}

impl DivergenceClass {
    /// Every divergence class, in the order `classify.rs` considers them.
    pub const ALL: [DivergenceClass; 6] = [
        DivergenceClass::CompileFailure,
        DivergenceClass::LinkFailure,
        DivergenceClass::RunCrash,
        DivergenceClass::ExitCodeMismatch,
        DivergenceClass::StdoutMismatch,
        DivergenceClass::Timeout,
    ];

    /// The token that matches the `class` field of an expected-divergence marker.
    pub fn label(self) -> &'static str {
        match self {
            DivergenceClass::CompileFailure => "compile_failure",
            DivergenceClass::LinkFailure => "link_failure",
            DivergenceClass::RunCrash => "run_crash",
            DivergenceClass::ExitCodeMismatch => "exit_code_mismatch",
            DivergenceClass::StdoutMismatch => "stdout_mismatch",
            DivergenceClass::Timeout => "timeout",
        }
    }

    /// Parse a divergence class from its token, ignoring surrounding whitespace and ASCII
    /// case. Case is ignored so a marker written in a different case is understood rather
    /// than turning a documented expected divergence into an unexplained failure.
    pub fn parse(text: &str) -> Option<DivergenceClass> {
        let wanted = text.trim();
        DivergenceClass::ALL
            .iter()
            .copied()
            .find(|candidate| wanted.eq_ignore_ascii_case(candidate.label()))
    }
}

impl fmt::Display for DivergenceClass {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.label())
    }
}

impl std::str::FromStr for DivergenceClass {
    type Err = HarnessError;

    fn from_str(text: &str) -> Result<DivergenceClass, HarnessError> {
        DivergenceClass::parse(text).ok_or_else(|| {
            HarnessError::new(
                "parsing a divergence class",
                format!(
                    "{text:?} names no divergence class; the closed set is: {}",
                    comma_separated(&DivergenceClass::ALL.map(DivergenceClass::label))
                ),
            )
        })
    }
}

/// The outcome of one comparison, from a closed and exhaustive set of six.
///
/// There is deliberately NO "skip because unsupported" verdict, and no code path anywhere
/// in the harness may silently drop a cell. An oracle whose tooling is genuinely absent is
/// reported as [`Verdict::Unavailable`] — loudly, and in the summary — which is what keeps
/// a modest environment from masquerading as a passing run.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Verdict {
    /// The compared outputs agree exactly: identical stdout bytes and identical exit
    /// status.
    Pass,
    /// A divergence that is documented rather than unexplained. This verdict has two
    /// forms, and both are reported as XFAIL:
    ///
    /// - a divergence covered by an **active marker** in the program's own expectation
    ///   record, citing a limitation the repository already documents; and
    /// - a comparison the program's own record **deliberately narrows away**, carrying its
    ///   reasoned exclusion in `impl_defined_notes` — the record format refuses to accept a
    ///   narrowing without one, so an undocumented exclusion cannot reach this verdict.
    ///
    /// In neither form does the classification change what the program does. A marker or a
    /// recorded exclusion changes how a divergence is CLASSIFIED, never whether the feature
    /// is EXERCISED: the applicable phases are attempted in order — compile, link, run,
    /// compare — and nothing in the harness may short-circuit a phase because a marker
    /// exists. Classification happens at the first terminal outcome or the completed
    /// comparison, so a compile failure, a link failure, a crash or a timeout is classified
    /// where it occurred rather than after a comparison that could not be reached.
    XFail,
    /// A marker is present but the divergence it describes has disappeared.
    ///
    /// This fails the run by default, following the standard convention that unexpected
    /// success is a failure. The justification is asymmetric cost: a stale marker is stale
    /// documented knowledge that will mislead the next reader, whereas retiring it is a
    /// trivial test-only edit. An environment-variable escape hatch exists for a
    /// marker-retirement window, and this verdict is always listed separately and
    /// prominently in the summary so it can never pass unnoticed.
    XPass,
    /// An undocumented divergence. It yields a self-contained artifact directory — a
    /// verbatim reproducer, its expectation record, a manifest recording the minimization
    /// status, exact reproduction commands, the captured outputs per compiler and per
    /// backend, an environment fingerprint and the computed difference — plus an entry in
    /// the findings register.
    ///
    /// The reproducer is a byte-for-byte copy of the corpus program: automated reduction is
    /// never performed during a run, and reduction is a supervised activity performed on the
    /// copy before a finding is promoted to the curated set. The reasons are recorded on
    /// `findings::Minimization`.
    ///
    /// A finding is a deliverable, not a defect to patch: no compiler source change is
    /// ever made in response to one.
    Finding,
    /// A divergence with no explanation at all, or an internal inconsistency in the suite
    /// itself. Fails the run.
    Fail,
    /// An oracle's tooling is genuinely absent from the environment, so this comparison
    /// could not be attempted.
    ///
    /// Always reported, never silent, and never a pass. Under the strict setting intended
    /// for continuous integration — where the toolchain is installed deliberately, so a
    /// missing oracle indicates a broken workflow rather than a modest machine — the
    /// driver escalates this to a failure.
    Unavailable,
}

impl Verdict {
    /// Every verdict, in reporting order. `report.rs` iterates it so the summary tally is
    /// complete and ordered, including zero rows.
    pub const ALL: [Verdict; 6] = [
        Verdict::Pass,
        Verdict::XFail,
        Verdict::XPass,
        Verdict::Finding,
        Verdict::Fail,
        Verdict::Unavailable,
    ];

    /// True for exactly the two verdicts that make a run fail: an unexplained failure and
    /// an unexpected success.
    ///
    /// The four verdicts permitted in a passing run are [`Verdict::Pass`],
    /// [`Verdict::XFail`], [`Verdict::Finding`] and [`Verdict::Unavailable`] — each of
    /// which is still reported in full. A finding does not fail the run because findings
    /// are deliverables; an unavailable oracle does not fail the run by default because
    /// the environment, not the compiler, is what is incomplete.
    pub fn fails_run(self) -> bool {
        matches!(self, Verdict::Fail | Verdict::XPass)
    }

    /// The uppercase report token, spelled as the requirements spell it.
    pub fn label(self) -> &'static str {
        match self {
            Verdict::Pass => "PASS",
            Verdict::XFail => "XFAIL",
            Verdict::XPass => "XPASS",
            Verdict::Finding => "FINDING",
            Verdict::Fail => "FAIL",
            Verdict::Unavailable => "UNAVAILABLE",
        }
    }

    /// Parse a verdict from its report token, ignoring surrounding whitespace and ASCII
    /// case, so that `report.rs` can re-read the machine-readable rows it wrote.
    pub fn parse(text: &str) -> Option<Verdict> {
        let wanted = text.trim();
        Verdict::ALL
            .iter()
            .copied()
            .find(|candidate| wanted.eq_ignore_ascii_case(candidate.label()))
    }
}

impl fmt::Display for Verdict {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.label())
    }
}

impl std::str::FromStr for Verdict {
    type Err = HarnessError;

    fn from_str(text: &str) -> Result<Verdict, HarnessError> {
        Verdict::parse(text).ok_or_else(|| {
            HarnessError::new(
                "parsing a verdict",
                format!(
                    "{text:?} names no verdict; the closed set is: {}",
                    comma_separated(&Verdict::ALL.map(Verdict::label))
                ),
            )
        })
    }
}

// Two kinds of text reach a report, a summary or a reproduction script from outside this
// harness: free text a maintainer wrote into an expectation record, and a banner an external
// tool printed when asked to identify itself. Neither may be emitted verbatim.
//
// A tab forges a column in a tab-separated report and can therefore relabel a verdict. A
// terminal escape sequence can hide a line, overwrite one already printed, or repaint a
// FINDING as a PASS in a maintainer's scrollback. A carriage return can erase the line it
// ends. None of these say anything about the compiler, and all of them corrupt the artifact
// the requirements ask for, so the functions below are the single place where such text is
// made safe. `manifest.rs` additionally REJECTS control characters at parse time, which is
// stronger; these functions are what protect the text the suite cannot refuse to accept —
// diagnostics naming an offending value, and the identification banner of a tool the suite
// did not write.

/// Characters that are not classed as controls but corrupt a report in exactly the same way,
/// and are therefore escaped alongside them.
///
/// The first twelve are the Unicode bidirectional formatting characters. They reorder the
/// *rendering* of text without changing its bytes, so a line can be made to display something
/// other than what it says — the mechanism behind the "Trojan Source" class of attack, and in
/// a verdict table the difference between reading `FAIL` and reading `PASS`. The last two are
/// the line and paragraph separators, which several Markdown and terminal renderers treat as
/// line breaks, so leaving them intact would let one report row become two.
const REPORT_HOSTILE_FORMATTING: &[char] = &[
    '\u{061c}', // ARABIC LETTER MARK
    '\u{200e}', // LEFT-TO-RIGHT MARK
    '\u{200f}', // RIGHT-TO-LEFT MARK
    '\u{202a}', // LEFT-TO-RIGHT EMBEDDING
    '\u{202b}', // RIGHT-TO-LEFT EMBEDDING
    '\u{202c}', // POP DIRECTIONAL FORMATTING
    '\u{202d}', // LEFT-TO-RIGHT OVERRIDE
    '\u{202e}', // RIGHT-TO-LEFT OVERRIDE
    '\u{2066}', // LEFT-TO-RIGHT ISOLATE
    '\u{2067}', // RIGHT-TO-LEFT ISOLATE
    '\u{2068}', // FIRST STRONG ISOLATE
    '\u{2069}', // POP DIRECTIONAL ISOLATE
    '\u{2028}', // LINE SEPARATOR
    '\u{2029}', // PARAGRAPH SEPARATOR
];

/// Whether `character` cannot appear literally in a report, a summary, a fingerprint or a
/// diagnostic without changing how that text behaves rather than merely what it says.
///
/// True for every character [`char::is_control`] reports — the C0 range, the delete character
/// and the C1 range — and for every entry of [`REPORT_HOSTILE_FORMATTING`].
///
/// This predicate is the **single authority** on the question, and it is deliberately shared
/// rather than reimplemented: [`sanitize_text_for_report`] escapes exactly the characters it
/// selects, [`CellKey::validate_stem`] refuses a name containing one, and `manifest.rs`
/// rejects one anywhere in a record — permitting only the line feed, and only inside a
/// heredoc body, by testing `must_escape_for_report(c) && c != '\n'`. One predicate with three
/// consumers cannot drift; three hand-written character tests would.
pub fn must_escape_for_report(character: char) -> bool {
    character.is_control() || REPORT_HOSTILE_FORMATTING.contains(&character)
}

/// Render text safely for a report, a summary, a fingerprint or a diagnostic.
///
/// Every character [`must_escape_for_report`] selects is replaced by a visible escape. The text can
/// then be read but can no longer act: no tab can forge a tab-separated column, no escape
/// introducer can begin a terminal sequence, no carriage return can erase the line it ends,
/// and no directional override can make a line render as something other than what it says.
/// The line feed is escaped too, because every consumer of this function writes a single line
/// and an embedded newline would split one record into two.
///
/// Escapes are written `\xNN` for a code point that fits in a byte and `\u{NNNN}` otherwise,
/// both of which are unambiguous and searchable. Printable text, including every non-ASCII
/// character that is neither a control nor a formatting character, passes through unchanged, so
/// a legitimate banner remains exactly as its tool printed it.
pub fn sanitize_text_for_report(raw: &str) -> String {
    let mut safe = String::with_capacity(raw.len());
    for character in raw.chars() {
        let code_point = u32::from(character);
        if !must_escape_for_report(character) {
            safe.push(character);
        } else if code_point <= 0xff {
            safe.push_str(&format!("\\x{code_point:02x}"));
        } else {
            safe.push_str(&format!("\\u{{{code_point:04x}}}"));
        }
    }
    safe
}

/// The characters a word may contain and still be safe to write into a shell script without
/// quoting.
///
/// Deliberately conservative: only characters that no POSIX shell treats specially in any
/// position. Everything else — whitespace, every redirection and list operator, every
/// quoting character, the expansion introducers, the pattern characters, the comment
/// character and the home-directory character — forces the quoted form.
const SHELL_SAFE_PUNCTUATION: &[char] = &['.', '_', '/', ':', '=', '@', '%', '+', ',', '-'];

/// Quote one word so that a POSIX shell reproduces it exactly.
///
/// A non-empty word made only of ASCII alphanumerics and [`SHELL_SAFE_PUNCTUATION`] is
/// returned unchanged, which keeps an ordinary command line readable. Anything else is
/// wrapped in single quotes, with each embedded single quote written as `'\''` — the standard
/// idiom, and the only one that is correct for **every** byte, because a single-quoted string
/// in a POSIX shell has no escape processing at all.
///
/// This is what makes a finding's reproduction commands "exact and copy-pasteable" rather
/// than merely plausible. A checkout path containing a space would otherwise split into two
/// arguments, and a path containing a semicolon, a backquote or a `$(` would be *executed*
/// rather than passed — which is precisely the difference between a reproduction script and
/// an injection. Control characters cannot reach this function from an expectation record,
/// because `manifest.rs` rejects them at parse time; a control character arriving from a
/// filesystem path is preserved verbatim inside the quotes, which is the only rendering that
/// still reproduces the path.
pub fn posix_quote(word: &str) -> String {
    let is_safe = !word.is_empty()
        && word
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || SHELL_SAFE_PUNCTUATION.contains(&c));
    if is_safe {
        return String::from(word);
    }
    let mut quoted = String::with_capacity(word.len() + 2);
    quoted.push('\'');
    for character in word.chars() {
        if character == '\'' {
            quoted.push_str("'\\''");
        } else {
            quoted.push(character);
        }
    }
    quoted.push('\'');
    quoted
}

/// Render an argument vector as a single POSIX shell line, each element quoted by
/// [`posix_quote`].
pub fn posix_command_line(argv: &[String]) -> String {
    argv.iter()
        .map(|word| posix_quote(word))
        .collect::<Vec<_>>()
        .join(" ")
}

/// Separator between the components of a cell slug.
///
/// A plus sign is chosen for one reason: [`encode_slug_component`] escapes it wherever it
/// occurs inside a component, so it never appears in encoded output. Splitting a slug on this
/// character therefore recovers exactly the four components that produced it, which is what
/// makes [`CellKey::slug`] injective rather than merely unlikely to collide. It is also safe
/// everywhere the harness uses a slug: no shell assigns it a special meaning, and no
/// supported filesystem reserves it.
const SLUG_SEPARATOR: char = '+';

/// Introducer for an escape sequence inside an encoded slug component.
///
/// The percent sign is itself escaped, as `%25`, so an escape sequence is always exactly
/// three characters long and can never be produced by passthrough input. That is what makes
/// the encoding reversible, and reversibility is precisely the property collision freedom
/// needs. Nothing in the harness decodes a slug; the escape is chosen to be reversible so
/// that collision freedom is a fact about the function rather than a hope about its inputs.
const SLUG_ESCAPE: char = '%';

/// Upper-case hexadecimal digits, indexed by nibble value.
///
/// Both index expressions in [`encode_slug_component`] are four bits wide, so the lookup
/// cannot be out of range: the encoder needs no fallback arm and cannot panic. That matters
/// because a slug is rendered on the failure path of every cell, where a panic would replace
/// a diagnosable divergence with a harness crash.
const SLUG_HEX_DIGITS: &[u8; 16] = b"0123456789ABCDEF";

/// Append one slug component to `encoded`, escaping it injectively into the passthrough
/// alphabet `[A-Za-z0-9_]` plus [`SLUG_ESCAPE`]-introduced hexadecimal escapes.
///
/// This is the single authority for turning an identity component into path text: every slug,
/// every workspace directory and every report row derives from it, so an identity can never be
/// rendered two ways.
///
/// A byte of the passthrough alphabet — ASCII letters, ASCII digits and the underscore — is
/// emitted verbatim, so the canonical corpus names stay readable: `01_integer_conversions`
/// encodes to itself. **Every other byte** — including the separator, the escape character
/// itself, and each individual byte of a multi-byte UTF-8 character — becomes [`SLUG_ESCAPE`]
/// followed by that byte's two upper-case hexadecimal digits. Encoding operates on bytes rather
/// than characters, so the result is always pure ASCII.
///
/// The mapping is injective, and the argument is short enough to check by hand: the passthrough
/// alphabet and the escape character are disjoint, an escape sequence has a fixed length of
/// three, and the two hexadecimal digits name exactly one byte, so the output can be read left
/// to right to recover the input byte sequence exactly. Folding could not offer that. A scheme
/// that folded every character outside the alphabet to a single underscore and collapsed runs
/// made `a_b`, `a__b`, `a b` and `a/b` indistinguishable, and made an empty name
/// indistinguishable from a name that was literally `unnamed`; under this encoding those six
/// inputs render as `a_b`, `a__b`, `a%20b`, `a%2Fb`, the empty string and `unnamed`.
///
/// Two further properties follow from that alphabet, and they are what make a slug safe to join
/// onto a path rather than merely tidy:
///
/// - The separator can never occur inside an encoded component, so splitting a slug on it
///   recovers exactly the components that produced it.
/// - No encoded component can be `.` or `..`, or contain a path separator, because the dot, the
///   forward slash and the backslash are all outside the passthrough alphabet. A slug is
///   therefore always a single path component that cannot traverse upwards, so joining it to
///   [`work_root`] always yields a direct child of that root.
///
/// Injectivity is what removes the need for a lock. The slug alone decides a cell's workspace
/// directory and the feature-area tests run concurrently, so under a lossy fold two distinct
/// identities that differed only outside the safe alphabet would share one workspace and
/// overwrite each other's artifacts mid-run — surfacing as an inexplicable divergence rather
/// than an error. A separate duplicate-slug detection pass would merely assert that theorem.
///
/// The mapping is a pure function of its input: no clock, no process identifier, no counter, no
/// randomness, no environment.
fn encode_slug_component(raw: &str, encoded: &mut String) {
    for byte in raw.bytes() {
        if byte.is_ascii_alphanumeric() || byte == b'_' {
            encoded.push(char::from(byte));
        } else {
            encoded.push(SLUG_ESCAPE);
            encoded.push(char::from(SLUG_HEX_DIGITS[usize::from(byte >> 4)]));
            encoded.push(char::from(SLUG_HEX_DIGITS[usize::from(byte & 0x0f)]));
        }
    }
}

/// Identifies exactly one cell of the build matrix: one program, on one target, at one
/// optimization level.
///
/// This is the unit of work the harness is organized around, and the sole input to a
/// cell's workspace path.
///
/// The two textual fields are private and [`CellKey::new`] is the only way to build one,
/// because this identity is not merely descriptive: it *decides* a filesystem path. The area
/// and program names are joined into [`CellKey::slug`], which becomes the name of the one
/// directory the cell may write into, and they are written into report rows, the
/// tab-separated summary and reproduction commands. A caller able to assign them — by struct
/// literal or by field assignment — could bypass [`CellKey::validate_stem`] and produce an
/// identity built from an empty string, a path fragment or text carrying control characters,
/// none of which could be traced back to a corpus file. Making the constructor the only door
/// turns "every identity is canonical" from a convention every caller must remember into a
/// property of the type.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct CellKey {
    area: String,
    program: String,
    target: Target,
    opt: OptLevel,
}

impl CellKey {
    /// Build a cell identity, rejecting an area or program name that is not a canonical
    /// corpus stem.
    ///
    /// This is the single construction point for the type, so every [`CellKey`] in existence
    /// has passed [`CellKey::validate_stem`] on both of its textual components. Consumers may
    /// therefore treat the canonical-stem rules as a type invariant instead of re-deriving
    /// them — [`fmt::Display`] and [`CellKey::slug`] both rely on exactly that, which is why
    /// neither can produce text that forges a report column or escapes a workspace directory.
    ///
    /// # Errors
    ///
    /// Returns an explanatory failure when either name is empty, is `.` or `..`, carries a
    /// path separator of either spelling, or contains whitespace or a character that cannot
    /// appear literally in a report. Each of those means the identity itself was assembled
    /// wrongly, which is a caller or corpus defect rather than something an environment can
    /// legitimately produce.
    pub fn new(
        area: impl Into<String>,
        program: impl Into<String>,
        target: Target,
        opt: OptLevel,
    ) -> HarnessResult<CellKey> {
        let key = CellKey {
            area: area.into(),
            program: program.into(),
            target,
            opt,
        };
        key.validate_identity()?;
        Ok(key)
    }

    /// The feature-area directory name, for example `04_bitfields`.
    pub fn area(&self) -> &str {
        &self.area
    }

    /// The program file stem, for example `003_compound_assignment`.
    pub fn program(&self) -> &str {
        &self.program
    }

    /// The target architecture this cell is built and executed for.
    pub fn target(&self) -> Target {
        self.target
    }

    /// The optimization level this cell is built at.
    pub fn opt(&self) -> OptLevel {
        self.opt
    }

    /// A deterministic, collision-free, filesystem-safe rendering of this identity, for
    /// example `01_integer_conversions+004_narrowing_conversions+aarch64+O1`.
    ///
    /// Collision freedom is a property of the rendering rather than an assumption about the
    /// corpus. Each component is escaped by [`encode_slug_component`], which is injective and
    /// never emits [`SLUG_SEPARATOR`], so the separators mark exactly the four component
    /// boundaries and two distinct identities cannot render to the same slug. That is what
    /// removes the need for any lock — two concurrent cells own distinct workspaces by
    /// construction, and no duplicate-detection pass is needed because such a pass would merely
    /// assert the theorem — and it holds for a curated finding reproducer whose name was never
    /// part of the numbered corpus just as it holds for `004_narrowing_conversions`.
    ///
    /// The join is positional: a separator is written before every component after the first,
    /// always three of them, never "one between the non-empty ones". That is load-bearing in
    /// the argument above, because a join that emitted a separator only when something had
    /// already been written would drop a boundary whenever a preceding component encoded to
    /// empty text.
    ///
    /// The result is always exactly one path component: it can contain no path separator of
    /// either spelling and can be neither `.` nor `..`, because the encoder escapes every byte
    /// outside `[A-Za-z0-9_]`. Joining it onto [`work_root`] therefore cannot reach outside the
    /// workspace root, which is the mechanical half of the write-path discipline.
    ///
    /// The slug contains no process identifier, no timestamp and no counter, so the same
    /// identity yields the same slug in every process and on every run. That is what makes a
    /// retained workspace reproducible and inspectable after the fact.
    pub fn slug(&self) -> String {
        let components: [&str; 4] = [
            self.area.as_str(),
            self.program.as_str(),
            self.target.short_name(),
            self.opt.short(),
        ];
        let mut rendered = String::new();
        for (index, component) in components.iter().enumerate() {
            if index > 0 {
                rendered.push(SLUG_SEPARATOR);
            }
            encode_slug_component(component, &mut rendered);
        }
        rendered
    }

    /// Reject an area or program name that is not a canonical corpus stem.
    ///
    /// The encoding in [`encode_slug_component`] is injective, so a strange name could
    /// never cause a workspace collision. This check exists for the other half of the
    /// problem: a name that is not a canonical stem means the identity itself was
    /// assembled wrongly — from an empty string, from a path fragment rather than a stem,
    /// or from text carrying control characters that would corrupt a report — and every one
    /// of those is a corpus or caller defect that must surface as an explanatory hard
    /// failure rather than as a strangely named directory nobody can trace back.
    ///
    /// A canonical stem is non-empty, is neither `.` nor `..`, carries no path separator of
    /// either spelling, and contains no whitespace and no control character. The
    /// corpus-wide convention is narrower still — lower-case ASCII, digits and underscores,
    /// as in `04_bitfields` and `003_compound_assignment` — but the check deliberately
    /// stops at the properties that actually threaten correctness, so that a future area or
    /// program name is not rejected for a stylistic reason.
    fn validate_identity(&self) -> HarnessResult<()> {
        CellKey::validate_stem("area", &self.area)?;
        CellKey::validate_stem("program", &self.program)
    }

    /// Apply the canonical-stem rules to one named component of this identity.
    ///
    /// Every diagnostic renders the offending value through [`sanitize_text_for_report`],
    /// so a name carrying a terminal escape cannot smuggle that escape into the failure
    /// message it provokes.
    fn validate_stem(role: &str, value: &str) -> HarnessResult<()> {
        let context = || format!("validating the {role} name of a cell identity");
        if value.is_empty() {
            return Err(HarnessError::new(
                context(),
                format!(
                    "the {role} name is empty; a cell identity is assembled from the corpus \
                     directory and file names, so an empty one means the identity was built \
                     from something other than a discovered corpus path"
                ),
            ));
        }
        let shown = sanitize_text_for_report(value);
        if value == "." || value == ".." {
            return Err(HarnessError::new(
                context(),
                format!(
                    "the {role} name is {shown:?}, which names a directory relative to another \
                     rather than a corpus stem; every area and program name is a plain stem"
                ),
            ));
        }
        if value.contains('/') || value.contains(std::path::MAIN_SEPARATOR) {
            return Err(HarnessError::new(
                context(),
                format!(
                    "the {role} name {shown:?} contains a path separator; the identity carries \
                     the area directory name and the program file stem, never a path fragment, \
                     because the cell's own paths are derived from the corpus root instead"
                ),
            ));
        }
        if value
            .chars()
            .any(|candidate| must_escape_for_report(candidate) || candidate.is_whitespace())
        {
            return Err(HarnessError::new(
                context(),
                format!(
                    "the {role} name {shown:?} contains whitespace or a character that cannot \
                     appear literally in a report; a stem carries neither, because it is written \
                     into report rows, workspace paths and reproduction commands, where such a \
                     character could forge a column, hide a line, or make a row render as \
                     something other than what it says"
                ),
            ));
        }
        Ok(())
    }
}

impl fmt::Display for CellKey {
    /// Human-readable form for failure messages, for example
    /// `04_bitfields/003_compound_assignment @ aarch64-linux-gnu -O1`.
    ///
    /// The two textual components are rendered through [`sanitize_text_for_report`]. Every
    /// [`CellKey`] has passed [`CellKey::validate_stem`], because [`CellKey::new`] is the only
    /// constructor, so that call is a no-op on every value the harness can actually build.
    /// It is applied regardless: this rendering reaches report rows and the tab-separated
    /// summary, where a single control character could forge a column or hide a line, and a
    /// guarantee is worth more when it is enforced at the point of output as well as at the
    /// point of construction than when one of the two is trusted to be sufficient.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{}/{} @ {} {}",
            sanitize_text_for_report(&self.area),
            sanitize_text_for_report(&self.program),
            self.target,
            self.opt
        )
    }
}

/// One fully resolved cell: its identity, the two files that define it, and the single
/// directory it is permitted to write into.
///
/// Both paths travel with the identity rather than being recomputed by each consumer,
/// because a cell must be reproducible from its source file and its expectation record
/// alone.
///
/// All four fields are private and [`Cell::new`] is the only way to build one, because this
/// type is where the read half and the write half of the path discipline are decided
/// together. The constructor proves that each input path resolves to a regular,
/// non-symbolic-link file strictly inside the corpus, that the two are same-stem siblings,
/// that their location agrees with the identity, and that the derived workspace is a direct
/// child of [`work_root`]. Every one of those guarantees is about a *combination* of fields,
/// so any of them could be defeated by assigning a single field afterwards — which is exactly
/// what a writable field permits. Because no field is writable, a value of this type cannot
/// exist in a state the constructor would have refused.
///
/// Only [`Cell::source`] is published, because that is the one path a consumer of a resolved cell
/// needs — the file it compiles and names in a report. The identity, the record and the derived
/// workspace are read inside this harness alone: [`fmt::Display`] renders all four for a
/// diagnostic, and `sandbox::for_resolved_cell` reads the identity and the workspace to prove its
/// own derivation agrees with this one. Publishing an accessor for the workspace in particular
/// would offer a caller the one value it must never act on independently, since the whole
/// mechanical content of the hermeticity contract is that a cell writes into the workspace the
/// sandbox allocated for it and nowhere else.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Cell {
    key: CellKey,
    source: PathBuf,
    expectation: PathBuf,
    workspace: PathBuf,
}

impl Cell {
    /// Canonical absolute path to the C program.
    ///
    /// This is the fully resolved path [`Cell::new`] proved to be a regular file inside the
    /// corpus, not the possibly indirect spelling that was handed in. Storing the resolved
    /// form means every consumer compiles, reads and reports the same file the constructor
    /// validated, and that a reproduction command carries a path with no `..` segment and no
    /// intermediate symbolic link for a maintainer to resolve by hand.
    pub fn source(&self) -> &Path {
        &self.source
    }

    /// Canonical absolute path to the sibling expectation record that governs this program.
    pub fn expectation(&self) -> &Path {
        &self.expectation
    }

    /// The one directory this cell may write into, derived from [`work_root`] and
    /// [`CellKey::slug`].
    ///
    /// Read-only on purpose. This single path is the whole mechanical content of the
    /// path discipline — a cell writes here and nowhere else — and [`Cell::new`] derives
    /// it from the identity and then proves it is a direct child of [`work_root`]. A consumer
    /// able to assign it could move a cell's writes anywhere on the machine while every report
    /// still showed the workspace path, which is the one failure that would leave no trace.
    pub fn workspace(&self) -> &Path {
        &self.workspace
    }

    /// Resolve a cell and derive its workspace.
    ///
    /// The workspace is derived rather than supplied, so the write path is decided in exactly one
    /// place: every cell writes beneath [`work_root`] and nowhere else. The two input paths are
    /// stored resolved, so a report and a reproduction command always name the files that were
    /// actually read.
    ///
    /// # Errors
    ///
    /// Validation is strict on purpose: every rejection below is a broken corpus invariant
    /// rather than a condition an environment can legitimately produce, so it becomes an
    /// explanatory hard failure naming the cell — never a quiet skip and never an opaque panic.
    ///
    /// Absoluteness and the right extension are necessary but nowhere near sufficient: both are
    /// satisfied by `/etc/shadow.c` and by a committed symbolic link pointing anywhere on the
    /// machine. Validation therefore covers three things:
    ///
    /// - the identity, through [`CellKey::validate_identity`]: the area and program names must
    ///   be canonical stems, so an identity assembled from an empty string, a path fragment or
    ///   text carrying control characters fails here rather than becoming a strangely named
    ///   directory nobody can trace back. Since [`CellKey::new`] is the only constructor for
    ///   that type, this re-asserts an invariant rather than establishing it; it is kept
    ///   because the workspace path is derived from the identity alone, and that derivation is
    ///   worth more when it cannot be reached by an unvalidated identity even if the type ever
    ///   grows a second constructor;
    /// - the read half of the path discipline, through [`require_contained_corpus_file`]: each
    ///   input must be an absolute path to a regular, non-symbolic-link file that resolves strictly
    ///   inside the corpus and carries the extension its role requires. A symbolic link is
    ///   refused rather than followed, because following one is how a corpus path comes to name
    ///   a file anywhere on the machine while every report still shows the corpus path — and a
    ///   discovered file is not merely read but compiled and *executed*;
    /// - the identity-to-location agreement: the two inputs must be same-directory siblings
    ///   sharing one stem, and the resolved location must agree with the key — the containing
    ///   directory with [`CellKey::area`] and the stem with [`CellKey::program`]. Without that
    ///   agreement a cell could be reported under one identity while compiling a different
    ///   program, and the workspace path, derived from the key alone, would name the wrong cell.
    ///
    /// The derived workspace is then asserted to be a direct child of [`work_root`]. That
    /// already follows from the slug being a single path component, and it is re-checked here
    /// because it is the one line on which the whole write-path argument rests.
    ///
    /// The two path fields of the returned cell hold the **canonical** forms, so a consumer can
    /// never operate on a different file from the one that was validated, and a reproduction
    /// command carries a path with no `..` segment and no intermediate symbolic link for a
    /// maintainer to resolve by hand.
    pub fn new(key: CellKey, source: PathBuf, expectation: PathBuf) -> HarnessResult<Cell> {
        let context = format!("resolving the input paths for {key}");
        key.validate_identity()?;
        let source = require_contained_corpus_file(&context, "source", &source, "c")?;
        let expectation = require_contained_corpus_file(
            &context,
            "expectation record",
            &expectation,
            "expected",
        )?;
        Cell::require_sibling_pair(&context, &source, &expectation)?;
        Cell::require_identity(&context, &key, &source)?;

        let root = work_root();
        let workspace = root.join(key.slug());
        if workspace.parent() != Some(root.as_path()) {
            return Err(HarnessError::new(
                format!("deriving the workspace path for {key}"),
                format!(
                    "{} is not a direct child of the work root {}; every cell writes into one \
                     directory immediately beneath that root and nowhere else, which is the \
                     property the suite's write-path discipline rests on",
                    shown_path(&workspace),
                    shown_path(&root)
                ),
            ));
        }
        Ok(Cell {
            key,
            source,
            expectation,
            workspace,
        })
    }

    /// Reject a program and record that are not same-directory siblings of one stem.
    ///
    /// The pairing is what makes "source file, build commands, and expected output recorded
    /// together" literally true, so a record borrowed from a neighbouring program — the one
    /// mistake that would leave every individual path check satisfied — is refused here.
    fn require_sibling_pair(context: &str, source: &Path, expectation: &Path) -> HarnessResult<()> {
        if source.parent() != expectation.parent() {
            return Err(HarnessError::new(
                context,
                format!(
                    "the program {} and the expectation record {} are not in the same directory; \
                     every record is the sibling of the program it governs, which is what makes \
                     a cell reproducible from those two files alone",
                    shown_path(source),
                    shown_path(expectation)
                ),
            ));
        }
        if source.file_stem() != expectation.file_stem() {
            return Err(HarnessError::new(
                context,
                format!(
                    "the program {} and the expectation record {} do not share a file stem; a \
                     record that governs a different program is the one mistake every individual \
                     path check would still accept",
                    shown_path(source),
                    shown_path(expectation)
                ),
            ));
        }
        Ok(())
    }

    /// Reject a resolved program path that disagrees with the identity it is being given.
    fn require_identity(context: &str, key: &CellKey, source: &Path) -> HarnessResult<()> {
        let area = source
            .parent()
            .and_then(Path::file_name)
            .and_then(|name| name.to_str());
        if area != Some(key.area.as_str()) {
            return Err(HarnessError::new(
                context,
                format!(
                    "the program {} lives in the feature-area directory {:?}, but this cell claims \
                     the area {:?}; the workspace path is derived from the identity alone, so a \
                     disagreement would file a cell's artifacts under another cell's name",
                    shown_path(source),
                    area.unwrap_or("<unreadable>"),
                    key.area
                ),
            ));
        }
        let stem = source.file_stem().and_then(|stem| stem.to_str());
        if stem != Some(key.program.as_str()) {
            return Err(HarnessError::new(
                context,
                format!(
                    "the program {} has the file stem {:?}, but this cell claims the program {:?}; \
                     a cell reported under one identity while compiling another program would make \
                     every verdict about it meaningless",
                    shown_path(source),
                    stem.unwrap_or("<unreadable>"),
                    key.program
                ),
            ));
        }
        Ok(())
    }
    /// The identity of this cell.
    pub fn key(&self) -> &CellKey {
        &self.key
    }
}

impl fmt::Display for Cell {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{} [source {}, expectation {}, workspace {}]",
            self.key,
            shown_path(&self.source),
            shown_path(&self.expectation),
            shown_path(&self.workspace)
        )
    }
}

/// One accumulated verdict: what a single oracle concluded about a single cell.
///
/// Outcomes are accumulated rather than asserted one at a time, because each area test
/// must enumerate every result in its report and stopping at the first divergence would
/// truncate it. Keying by oracle as well as by cell is what lets a construct be excluded
/// from one oracle while remaining fully compared under the others.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Outcome {
    key: CellKey,
    oracle: Oracle,
    verdict: Verdict,
    class: Option<DivergenceClass>,
    marker_id: Option<String>,
    detail: String,
}

impl Outcome {
    /// Record one outcome.
    ///
    /// An empty `detail` is replaced with a sentence naming the verdict, the oracle and the
    /// cell, because a run-failing outcome carrying an opaque message is what makes a real
    /// divergence impossible to act on.
    ///
    /// `detail` and `marker_id` are both passed through [`sanitize_text_for_report`] here, at
    /// the single point where an outcome comes into existence. That is not defensive
    /// decoration: `detail` is assembled from material the harness does not author — a
    /// compiler's diagnostics, a program's own stdout, a field of an expectation record — and
    /// [`Outcome`]'s [`fmt::Display`] renders the whole outcome as **one line** of the verdict
    /// table and of the tab-separated summary. Left raw, a single line feed in a compiler
    /// message would split one verdict row into two, a tab would forge a column in the
    /// machine-readable summary, a carriage return would erase the verdict that preceded it on
    /// the line, and a directional override or an escape introducer would let a row render as
    /// something other than what it says. Any of those turns a report a maintainer is meant to
    /// act on into one that cannot be trusted, and the material that would carry them is
    /// exactly the material a real divergence produces.
    ///
    /// Sanitizing at construction rather than at each use is what makes the guarantee hold: an
    /// outcome cannot exist in an unsafe state, so no present or future consumer can render one
    /// unsafely by forgetting. The escaping is visible and reversible by eye — `\x0a` for a
    /// line feed — so nothing a reader needs is lost.
    ///
    /// Raw, unescaped bytes belong only in the captured-output artifacts a finding directory
    /// holds, where each stream is written to its own file, byte for byte, and is never mixed
    /// into a line-oriented report.
    pub fn new(
        key: CellKey,
        oracle: Oracle,
        verdict: Verdict,
        class: Option<DivergenceClass>,
        marker_id: Option<String>,
        detail: impl Into<String>,
    ) -> Outcome {
        let supplied = detail.into();
        // Emptiness is judged on the supplied text so that a detail made only of whitespace,
        // including a lone line feed, still selects the explanatory fallback rather than
        // surviving as the escape sequence that whitespace would sanitize into.
        let chosen = if supplied.trim().is_empty() {
            let severity = if verdict.fails_run() {
                "this verdict fails the run, so the absent detail is itself a defect in the \
                 caller that recorded it"
            } else {
                "no further detail was recorded"
            };
            format!("{verdict} from {oracle} for {key} carries no detail: {severity}")
        } else {
            supplied
        };
        Outcome {
            key,
            oracle,
            verdict,
            class,
            marker_id: marker_id.map(|marker| sanitize_text_for_report(&marker)),
            detail: sanitize_text_for_report(&chosen),
        }
    }

    /// The cell this outcome is about.
    pub fn key(&self) -> &CellKey {
        &self.key
    }

    /// Which oracle reached this conclusion.
    pub fn oracle(&self) -> Oracle {
        self.oracle
    }

    /// The conclusion itself.
    pub fn verdict(&self) -> Verdict {
        self.verdict
    }

    /// The shape of the divergence, when there was one. `None` for an agreement and for an
    /// oracle that could not be attempted.
    pub fn class(&self) -> Option<DivergenceClass> {
        self.class
    }

    /// Identifier of the expected-divergence marker that explains this outcome, present for
    /// an expected divergence and for an unexpected success, absent otherwise.
    ///
    /// Already sanitized for single-line rendering by [`Outcome::new`].
    pub fn marker_id(&self) -> Option<&str> {
        self.marker_id.as_deref()
    }

    /// Everything a reader needs to understand the outcome without re-running it: the first
    /// divergent line and byte offset, both exit statuses, and the command lines involved.
    ///
    /// Already sanitized for single-line rendering by [`Outcome::new`], so this is safe to
    /// write into a report row, a summary column or a diagnostic without further treatment.
    pub fn detail(&self) -> &str {
        &self.detail
    }
}

impl fmt::Display for Outcome {
    /// One-line rendering used verbatim in both the driver's verdict table and its failure
    /// messages, so a failing run reproduces the same text the report contains.
    ///
    /// "One line" is a guarantee rather than an expectation. Of the five rendered components,
    /// three are enumerations with fixed spellings, [`CellKey`]'s own rendering sanitizes its
    /// textual halves, and the two free-text components were sanitized by [`Outcome::new`] at
    /// construction. No value of this type can therefore render as more or fewer than one line,
    /// which is what lets a report row be counted as one outcome.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "[{}] {} {}", self.verdict, self.oracle, self.key)?;
        if let Some(class) = self.class {
            write!(f, " (class {class})")?;
        }
        if let Some(marker) = &self.marker_id {
            write!(f, " (marker {marker})")?;
        }
        write!(f, ": {}", self.detail)
    }
}

/// A harness failure that is the suite's or the corpus's fault rather than the
/// environment's.
///
/// A tool an environment can legitimately lack is not an error: it becomes
/// [`Verdict::Unavailable`] and is reported in the summary. This type is reserved for a
/// broken invariant — an unreadable corpus directory, an absent compiler under test, a
/// marker citing a document that does not exist — and always surfaces as a hard failure.
///
/// Context and cause are carried separately so a message says what the harness was doing
/// as well as what went wrong, which makes a failure actionable without a stack trace.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct HarnessError {
    context: String,
    cause: String,
}

impl HarnessError {
    /// Build an error from its context and its cause.
    pub fn new(context: impl Into<String>, cause: impl Into<String>) -> HarnessError {
        HarnessError {
            context: context.into(),
            cause: cause.into(),
        }
    }

    /// What the harness was attempting, phrased as a gerund, for example
    /// `resolving the source path for 04_bitfields/002_read_write @ i686-linux-gnu -O1`.
    pub fn context(&self) -> &str {
        &self.context
    }

    /// What went wrong, in enough detail to act on without re-running.
    pub fn cause(&self) -> &str {
        &self.cause
    }
}

impl fmt::Display for HarnessError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "conformance harness failed while {}: {}",
            self.context, self.cause
        )
    }
}

impl std::error::Error for HarnessError {}

impl From<std::io::Error> for HarnessError {
    /// Adapt a filesystem or process error so the question-mark operator works throughout
    /// the harness.
    ///
    /// The context is generic, so a call site that knows what it was doing should build the
    /// error with [`HarnessError::new`] instead. The underlying message is preserved
    /// verbatim.
    fn from(error: std::io::Error) -> HarnessError {
        HarnessError::new(
            "performing a filesystem or process operation",
            error.to_string(),
        )
    }
}

/// Result alias used throughout the harness.
pub type HarnessResult<T> = Result<T, HarnessError>;

// Every filesystem location the harness touches is derived from the roots below, so
// the write-path discipline can be checked in one place: the suite reads a program's source and its
// expectation record, and writes only beneath the work, report and findings roots.

/// Absolute path to the package root, taken from the manifest directory Cargo provides at
/// compile time.
///
/// Resolved from the manifest directory rather than the working directory because
/// `cargo test` makes no guarantee about a test process's working directory.
///
/// # The one build-time requirement in the whole suite
///
/// `env!` is deliberate and load-bearing: this value must be the package root, and there is no
/// run-time source for it that a test process can trust. It is also the one thing here that a
/// **bare `rustc`** does not supply. Cargo defines `CARGO_MANIFEST_DIR` for every target it builds,
/// so `cargo test` and `cargo clippy` need nothing extra; a direct
/// `rustc --test --emit=metadata tests/conformance.rs` — the type-check the suite's own contract
/// offers for a checkout that carries it ahead of the compiler tree — defines nothing, and stops
/// here with "environment variable `CARGO_MANIFEST_DIR` not defined at compile time". Supply it on
/// the command line in that case: `CARGO_MANIFEST_DIR="$(pwd)" rustc …`, run from the repository
/// root.
///
/// The contrast with how the compiler under test is located is intentional, and is the reason only
/// this one value behaves this way. `env::CARGO_BIN_EXE_BCC` reads Cargo's binary-path variable
/// through `option_env!` rather than `env!`, so a package that declares no `bcc` binary target
/// still builds and the missing compiler becomes an explanatory run-time failure instead of a
/// build error. The manifest directory cannot be deferred that way: without it the suite has no
/// root to resolve a corpus path from, and so nothing to explain the failure with.
pub fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Absolute path to the corpus root, which holds the feature-area directories, the
/// registers, the fixture header, the maintenance tooling and the curated findings.
///
/// The corpus is discovered by scanning this directory, so a program needs **no code
/// registration**: nothing here, and no list anywhere in the harness, enumerates the programs.
///
/// That is not the same as "no harness change". Adding a program takes its `.c` source and its
/// sibling `.expected` record, **and** an increment of the area's `program_count` in [`AREAS`] —
/// because `report.rs` compares the declared count against the discovered one and reports a
/// disagreement as a corpus defect. The declared count is what makes a *silently missing* program
/// detectable, so it is a deliberate second edit rather than an oversight.
pub fn corpus_root() -> PathBuf {
    manifest_dir().join("tests").join("conformance")
}

/// The variable Cargo uses to redirect the build directory, honoured here under validation.
///
/// Named as a constant because it is catalogued: `env.rs` lists it among the variables the
/// pre-flight report states, and [`build_root`] is the only reader of it.
pub const VAR_CARGO_TARGET_DIR: &str = "CARGO_TARGET_DIR";

/// Absolute path to the Cargo build directory, the only place the harness writes.
///
/// A configured target directory is honoured, so a build that redirects its output does not
/// leave the harness writing into a directory the build does not own. A relative
/// configured value is resolved against the package root rather than the working
/// directory, so the result is absolute whenever [`manifest_dir`] is.
///
/// # Why the configured value is validated rather than taken as given
///
/// This one variable decides where every workspace, every report and every finding artifact is
/// written, so it is the widest-reaching input the harness reads from its environment — wider
/// than any `BCC_*` override, each of which selects a single tool. Taking it verbatim would let
/// three distinct defects through, and [`validated_target_dir`] closes all three:
///
/// - a value carrying a control, escape or bidirectional formatting character would be rendered
///   into report lines and reproduction commands, where it could forge a tab-separated column or
///   repaint a line — the same hazard [`sanitize_text_for_report`] exists to close everywhere
///   else;
/// - a value naming a path with a parent-directory component would place the build roots
///   somewhere no containment guard could describe, and every "beneath the build directory"
///   claim in this suite would become unverifiable;
/// - a value that is not valid text could not be written into a reproduction command at all, so
///   a maintainer copying one out of a finding would be given a path naming a *different*
///   directory from the one that ran.
///
/// A rejected value falls back to the package-relative default and is **reported**, never
/// silently honoured: `env.rs` surfaces [`target_dir_rejection`] in the pre-flight capability
/// report so the run states plainly that it ignored the setting and why.
pub fn build_root() -> PathBuf {
    match validated_target_dir() {
        Ok(Some(configured)) => configured,
        Ok(None) | Err(_) => manifest_dir().join("target"),
    }
}

/// Why a configured build directory was refused, or `None` when there is nothing to report.
///
/// `Some(reason)` means [`VAR_CARGO_TARGET_DIR`] was set to a value this harness will not write
/// beneath, and that [`build_root`] fell back to the package-relative default. The reason is
/// already safe to render.
pub fn target_dir_rejection() -> Option<String> {
    validated_target_dir().err()
}

/// The configured build directory, validated, or `None` when the variable is unset or empty.
///
/// # Errors
///
/// Returns an already-sanitized sentence naming the defect when the value is not valid text,
/// carries a character that cannot appear literally in a report, or is not a plain absolute or
/// package-relative path.
fn validated_target_dir() -> Result<Option<PathBuf>, String> {
    let Some(raw) = std::env::var_os(VAR_CARGO_TARGET_DIR).filter(|value| !value.is_empty()) else {
        return Ok(None);
    };
    let Some(text) = raw.to_str() else {
        return Err(format!(
            "{VAR_CARGO_TARGET_DIR} is set to a value that is not valid UTF-8, so it could not be \
             written into a report line or a reproduction command; the package-relative default \
             build directory is used instead"
        ));
    };
    let shown = sanitize_text_for_report(text);
    if text.chars().any(must_escape_for_report) {
        return Err(format!(
            "{VAR_CARGO_TARGET_DIR} is set to {shown:?}, which contains a character that cannot \
             appear literally in a report — a control character, an escape introducer or a \
             directional override could forge a column or repaint a line in every artifact this \
             suite writes; the package-relative default build directory is used instead"
        ));
    }
    let configured = PathBuf::from(text);
    for component in configured.components() {
        match component {
            Component::Normal(_) | Component::RootDir | Component::Prefix(_) => {}
            Component::CurDir | Component::ParentDir => {
                return Err(format!(
                    "{VAR_CARGO_TARGET_DIR} is set to {shown:?}, which contains a relative \
                     directory component; the build roots must sit at a path every containment \
                     guard in this suite can describe, so the package-relative default build \
                     directory is used instead"
                ));
            }
        }
    }
    let resolved = if configured.is_absolute() {
        configured
    } else {
        manifest_dir().join(configured)
    };

    // **Every existing level** of the resolved path must be a real directory — not merely the final
    // component. Checking the leaf alone would leave the more dangerous arrangement untouched: a
    // link planted at any level *above* the build directory relocates every workspace, every report
    // and every finding this run publishes, and relocates the ownership-aware purges those roots
    // perform, so a removal aimed inside the build tree would execute outside it — while the leaf
    // itself was a perfectly ordinary directory and every artifact still named the path that was
    // asked for. A level that does not exist yet ends the walk and is accepted, because the build
    // directory is ordinarily created on first use and refusing that would reject a legitimate
    // first run; `create_directory_chain_below` then verifies each level as it establishes it.
    if let Some(defect) = directory_ancestry_defect(&resolved) {
        return Err(format!(
            "{VAR_CARGO_TARGET_DIR} is set to {shown:?}, whose chain of directories cannot be \
             trusted: {defect}. The package-relative default build directory is used instead"
        ));
    }

    Ok(Some(resolved))
}

/// Root of the per-cell workspaces, one subdirectory per [`CellKey::slug`].
///
/// A workspace is removed once its cell has passed and retained when it has not, so a
/// failing cell leaves behind the artifacts needed to investigate it. The retention setting
/// in `env.rs` keeps passing workspaces too.
pub fn work_root() -> PathBuf {
    build_root().join("conformance-work")
}

/// Root of the run's reports: one Markdown and one tab-separated file per feature area,
/// plus the run summary in both forms.
///
/// Each area writes only its own file, so concurrently executing areas never contend, and
/// the summary is finalized by a check-and-write that succeeds once every area file exists,
/// which needs no ordering between tests.
pub fn report_root() -> PathBuf {
    build_root().join("conformance-report")
}

/// Root of the findings generated by the current run.
///
/// Distinct from the curated finding set committed under [`corpus_root`], which is a
/// deliverable: no function here returns a writable handle to it, so an in-progress run
/// cannot pollute it.
pub fn findings_root() -> PathBuf {
    build_root().join("conformance-findings")
}

/// The corpus root with every symbolic link resolved.
///
/// Resolved rather than merely joined, because containment can only be decided between two
/// paths that have both been reduced to their real locations: comparing a real path against an
/// unresolved root would reject a legitimate file whenever the build tree itself sits behind a
/// link, and comparing an unresolved path against an unresolved root would accept an escape.
///
/// An unreadable corpus root is a hard failure. It is the one directory the suite cannot do
/// without, and a run that quietly discovered no programs would report success while testing
/// nothing.
///
/// # Errors
///
/// Fails when [`corpus_root`] cannot be canonicalized: the directory is absent, is unreadable, or
/// lies behind a link that does not resolve. The underlying cause is named, because the remedy
/// differs — a wrong checkout layout and a permission problem look identical without it.
pub fn canonical_corpus_root() -> HarnessResult<PathBuf> {
    let declared = corpus_root();
    declared.canonicalize().map_err(|error| {
        HarnessError::new(
            "resolving the corpus root",
            format!(
                "{} could not be resolved: {error}; the corpus is the directory the suite reads \
                 every program and every expectation record from, so a root that cannot be \
                 resolved is a hard failure rather than an empty run",
                shown_path(&declared)
            ),
        )
    })
}

// Constraint four permits the suite to compile and execute the programs it discovers, and
// requires those programs not to reach the network or any path outside their working
// directory. Nothing here enforces that requirement on a running program — no syscall or
// network isolation exists in this harness — so it is discharged by authoring every corpus
// program to take its whole input from literals in its own source. That is only auditable
// while the set of things the suite will compile is exactly the set of files committed under
// the corpus root, because a program is an input the suite hands to a compiler and then
// *runs*. A file that reaches the matrix from elsewhere is arbitrary code execution with the
// suite's privileges, and a file the suite merely *reads* from elsewhere is disclosure: its
// bytes are copied into a finding artifact and a report.
//
// Two properties are therefore established before any discovered path is used, and they are
// established here so that every caller — cell construction, record loading, area discovery —
// gets the same answer:
//
//   1. the path names an existing regular file, not a symbolic link and not a directory,
//      device node, socket or FIFO;
//   2. after canonicalization the path lies strictly beneath the canonical corpus root.
//
// The order matters. Testing the link status first, with `symlink_metadata`, means a committed
// symbolic link is refused outright rather than silently followed — a link is not a program,
// and accepting one would let the corpus name a file it does not contain. Canonicalizing
// second means an intermediate directory that *is* a link is resolved and then judged on where
// it actually leads, so a link that stays inside the corpus is harmless and one that escapes
// upward is rejected by the containment test rather than by a special case.
//
// Containment is compared component by component rather than by string prefix. A prefix test
// on text answers "does `/corpus-evil/x` start with `/corpus`" with yes, which is wrong; a
// component test answers it with no, because `corpus-evil` and `corpus` are different
// components. This is the classic path-prefix confusion, and comparing components is the only
// spelling that does not have it.

/// Require that `path` is an existing regular file, rejecting symbolic links.
///
/// `context` describes the operation in progress and is used verbatim in the error, so the
/// failure names what the harness was doing as well as what was wrong.
///
/// [`std::fs::symlink_metadata`] is used rather than [`std::fs::metadata`] precisely because
/// it does **not** follow a final symbolic link: the link itself is inspected, so a link is
/// reported as a link and refused. Following it would mean the corpus could name any file on
/// the machine — `/etc/shadow` renamed to something ending in `.c` satisfies every other
/// check this harness makes — and that file's bytes would then be compiled, executed and
/// copied into a report.
///
/// # Errors
///
/// Three conditions fail, each reported with `context` and the path. The entry cannot be
/// inspected, so nothing is known about it; the entry is a symbolic link, which is refused rather
/// than followed; or the entry exists but is not a regular file, which covers a directory and also
/// a device node, socket or FIFO, any of which can block a read without end.
pub fn require_regular_file(context: &str, path: &Path) -> HarnessResult<()> {
    let metadata = std::fs::symlink_metadata(path).map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!(
                "{} could not be inspected: {error}; every path the suite compiles, runs or \
                 reads must be a regular file that exists in the checkout",
                shown_path(path)
            ),
        )
    })?;
    let file_type = metadata.file_type();
    if file_type.is_symlink() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} is a symbolic link; the suite refuses to follow one, because a link lets the \
                 corpus name a file it does not contain and every discovered file is compiled, \
                 executed and copied into a report",
                shown_path(path)
            ),
        ));
    }
    if !file_type.is_file() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} is not a regular file; a directory, device node, socket or FIFO cannot be a \
                 program or an expectation record, and reading one can block indefinitely",
                shown_path(path)
            ),
        ));
    }
    Ok(())
}

/// Require that `path` lies strictly beneath `root` once both have been canonicalized, and
/// return the canonical form of `path`.
///
/// Both sides are canonicalized so that the comparison is between two fully resolved,
/// absolute, link-free paths. Canonicalizing only one side would compare a resolved path
/// against an unresolved root and could reject a legitimate file — for instance when the
/// checkout itself is reached through a symbolic link, which is ordinary on a build machine.
///
/// "Strictly beneath" means the root's component sequence is a proper prefix of the path's.
/// The root itself is therefore not contained in itself, which is correct here: a root is a
/// directory and every caller is asking about a file.
///
/// # Errors
///
/// Four conditions fail. `root` cannot be canonicalized, so containment cannot be decided at all;
/// `path` cannot be canonicalized, which includes the ordinary case of a path that does not exist;
/// the resolved path leaves the resolved root, which is reported with both resolved forms so the
/// escape is visible rather than merely asserted; or the resolved path *is* the root, which is no
/// file. A component-wise comparison decides the third, so a sibling directory whose name merely
/// begins with the root's name is not mistaken for a child.
pub fn ensure_within(context: &str, root: &Path, path: &Path) -> HarnessResult<PathBuf> {
    let canonical_root = root.canonicalize().map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!(
                "the containment root {} could not be resolved: {error}; the suite cannot prove \
                 a file lies inside a directory it cannot find",
                shown_path(root)
            ),
        )
    })?;
    let canonical_path = path.canonicalize().map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!(
                "{} could not be resolved: {error}; containment is decided on the fully resolved \
                 path so that no symbolic link along the way can change the answer",
                shown_path(path)
            ),
        )
    })?;

    let mut path_components = canonical_path.components();
    for root_component in canonical_root.components() {
        if path_components.next() != Some(root_component) {
            return Err(HarnessError::new(
                String::from(context),
                format!(
                    "{} resolves to {}, which is not inside {}; the suite compiles, executes and \
                     reports only files committed beneath that directory, so a path that leaves \
                     it is refused rather than followed",
                    shown_path(path),
                    shown_path(&canonical_path),
                    shown_path(&canonical_root)
                ),
            ));
        }
    }
    if path_components.next().is_none() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} resolves to the containment root {} itself rather than to a file beneath it",
                shown_path(path),
                shown_path(&canonical_root)
            ),
        ));
    }
    Ok(canonical_path)
}

/// Require that `path` lies beneath [`corpus_root`], and return its canonical form.
///
/// This is the containment check every consumer of a discovered path uses. It is a thin
/// specialization of [`ensure_within`] so that the corpus root is named in exactly one place
/// and cannot drift between callers.
///
/// # Errors
///
/// Exactly [`ensure_within`]'s, with [`corpus_root`] as the root: an unresolvable root, an
/// unresolvable or non-existent `path`, a resolved path outside the corpus, or a path that
/// resolves to the corpus root itself.
pub fn ensure_within_corpus(context: &str, path: &Path) -> HarnessResult<PathBuf> {
    ensure_within(context, &corpus_root(), path)
}

/// Validate one corpus input and return its resolved path.
///
/// Four conditions must hold, and each closes a distinct way a path could name something the
/// suite must not read:
///
/// - the path is absolute, so the file a cell names never depends on the working directory,
///   about which the test harness makes no guarantee;
/// - the entry is a regular file and **not a symbolic link**, delegated to
///   [`require_regular_file`];
/// - the resolved path lies strictly beneath the corpus root, delegated to
///   [`ensure_within_corpus`], which also rejects a file whose parent directory is a link out
///   of the corpus, since resolution reduces the whole path;
/// - the extension is the one the role requires, so a program and its record cannot be
///   swapped.
///
/// The two properties in the middle are delegated rather than repeated so that this funnel and
/// the primitives above cannot disagree about what "inside the corpus" means.
///
/// The returned path is the resolved one. Callers record it rather than the path they were
/// given, so that a report and a reproduction command always name the file that was actually
/// read.
pub fn require_contained_corpus_file(
    context: &str,
    role: &str,
    path: &Path,
    extension: &str,
) -> HarnessResult<PathBuf> {
    if !path.is_absolute() {
        return Err(HarnessError::new(
            context,
            format!(
                "the {role} path {} is not absolute; corpus paths are derived from the package \
                 manifest directory so that a cell never depends on the working directory",
                shown_path(path)
            ),
        ));
    }

    let scoped = format!("{context}: the {role} path");
    require_regular_file(&scoped, path)?;
    let resolved = ensure_within_corpus(&scoped, path)?;

    let found = resolved
        .extension()
        .and_then(|value| value.to_str())
        .map(String::from);
    if found.as_deref() != Some(extension) {
        return Err(HarnessError::new(
            context,
            format!(
                "the {role} path {} does not have the required extension {extension:?}; every \
                 program in the corpus is a .c file paired with a sibling .expected record",
                shown_path(&resolved)
            ),
        ));
    }

    Ok(resolved)
}

// =================================================================================================
// Stable digests
//
// Two things in this suite are named by a hash of what they describe: a finding's artifact directory
// and a run's configuration. Both names outlive the process that produced them and are compared
// between runs — one to recognise the same finding again, the other to recognise the same
// configuration — so the hash has one absolute requirement, and it is not speed or distribution but
// *permanence*: the same input must produce the same digits in every process, on every machine and
// under every toolchain version, forever.
//
// The standard library's default hasher is explicitly documented as unstable across releases, so it
// cannot be used for either. FNV-1a is used instead: four lines of arithmetic with a fixed published
// specification and no state beyond a single accumulator.
// =================================================================================================

/// FNV-1a 64-bit offset basis.
const FNV_OFFSET_BASIS: u64 = 0xcbf2_9ce4_8422_2325;

/// FNV-1a 64-bit prime.
const FNV_PRIME: u64 = 0x0000_0100_0000_01b3;

/// Byte separating the components of a hashed identity.
///
/// A zero byte, which cannot occur in any component, so the concatenation is unambiguous and two
/// different component lists cannot hash the same input.
const DIGEST_SEPARATOR: u8 = 0;

/// Hexadecimal digits in a rendered digest, which is the whole 64 bits.
pub const DIGEST_HEX_DIGITS: usize = 16;

/// Hash a component list with FNV-1a, 64-bit.
///
/// Not a cryptographic hash, and it does not need to be: nothing here defends against an adversary
/// choosing colliding inputs, because every input is text this suite produced from its own corpus,
/// its own configuration and its own capability record. What it must do is separate the identities
/// those inputs actually produce, and report rather than assume when two of them coincide.
pub fn fnv1a64(components: &[&str]) -> u64 {
    let mut hash = FNV_OFFSET_BASIS;
    for (index, component) in components.iter().enumerate() {
        if index > 0 {
            hash = fnv1a64_step(hash, DIGEST_SEPARATOR);
        }
        hash = fnv1a64_bytes_from(hash, component.as_bytes());
    }
    hash
}

/// Hash one byte slice with FNV-1a, 64-bit, under the same specification as [`fnv1a64`].
///
/// Exists because the corpus-content identity has to digest **bytes**, not text. Converting a file
/// lossily to a string first would map every invalid UTF-8 sequence to the same replacement
/// character, so two files differing only in such a sequence would digest alike — which is precisely
/// the silent equality a content identity exists to rule out.
///
/// The arithmetic is shared with [`fnv1a64`] through [`fnv1a64_bytes_from`] rather than repeated,
/// for the reason [`stable_digest`] gives: two copies of a hash are two chances for one of them to
/// drift, and a digest that differs by call site reports a mismatch between two artefacts that
/// describe the same thing.
pub fn fnv1a64_bytes(bytes: &[u8]) -> u64 {
    fnv1a64_bytes_from(FNV_OFFSET_BASIS, bytes)
}

/// Absorb a byte slice into an in-progress FNV-1a accumulator.
fn fnv1a64_bytes_from(mut hash: u64, bytes: &[u8]) -> u64 {
    for byte in bytes {
        hash = fnv1a64_step(hash, *byte);
    }
    hash
}

/// Absorb one byte into an in-progress FNV-1a accumulator: exclusive-or, then multiply.
///
/// The single copy of the arithmetic in this suite.
fn fnv1a64_step(hash: u64, byte: u8) -> u64 {
    (hash ^ u64::from(byte)).wrapping_mul(FNV_PRIME)
}

/// A component list as [`DIGEST_HEX_DIGITS`] lower-case hexadecimal digits.
///
/// The whole digest is rendered rather than a remainder of it. A truncated digest is a smaller
/// keyspace, and a smaller keyspace collides silently — which for a name that identifies an artifact
/// means one artifact quietly standing in for another.
pub fn digest_hex(components: &[&str]) -> String {
    format!(
        "{:0width$x}",
        fnv1a64(components),
        width = DIGEST_HEX_DIGITS
    )
}

// =================================================================================================
// The run generation
//
// Every artifact the suite leaves behind belongs to exactly one run, and a reader must be able to
// tell which. Without that, the most damaging failure in a reporting pipeline is available: an area
// report left behind by a previous — possibly reduced, possibly differently configured — run is
// indistinguishable from one this run produced, so a summary can be assembled from a blend of two
// and presented as the account of one.
//
// The generation is established once per process and answers two different questions with two
// different values, because conflating them would make one of the answers useless:
//
// - [`RunGeneration::token`] identifies *this process's* run. It is unpredictable, which is what
//   makes it useful for claiming a one-shot action and for naming a temporary file no concurrent
//   writer can also choose. It is deliberately **never** rendered into a report's Markdown or into
//   any field of either summary: an area report's Markdown is documented as byte-identical for
//   identical inputs and a token would break that on every run. It appears in exactly two places
//   outside those artifacts: the `token=` field of an area report's generation preamble, which is a
//   comment line whose only consumer is the machine check that refuses a report an earlier run of an
//   identical configuration left behind; and the `run_token` line of a finding's `environment.txt`,
//   so a maintainer holding a copied or archived finding can tell which run produced it. Both are
//   argued where they are written, in `report.rs`'s generation-identity section and in
//   `findings.rs`'s environment renderer.
// - [`RunGeneration::configuration`] identifies the *configuration* the run was performed under. It
//   is a pure function of that configuration, so it differs the moment one run was reduced, filtered
//   or pointed at another compiler, which is exactly what distinguishes a full run's numbers from a
//   quick run's. That is the value a report may carry.
//
//   Being a pure function of the configuration is not the same as being constant between two runs,
//   and the difference matters to anyone diffing two summaries. The configuration includes the
//   resolved identity of every tool, and a tool's identity includes how it was established; under
//   strict mode a runner is established by attestation, which requires it to print a token derived
//   from this run and exit with a status derived from it, and that required status is part of the
//   record. So this value legitimately differs between two identically configured runs on one
//   machine whenever a runner was attested. The stability promise therefore belongs to the area
//   Markdown, which renders neither value; `env.rs`'s
//   `Capabilities::configuration_fingerprint` states the consequence field by field.
// =================================================================================================

/// Identity of one run of the suite.
///
/// Obtained through [`run_generation`], which builds it once per process. The fields are private
/// because each carries an invariant the constructor establishes: the token must be unique to this
/// process, and the configuration fingerprint must be a pure function of the configuration and of
/// nothing else. A writable field would let one area file claim to belong to a run it did not.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct RunGeneration {
    token: String,
    configuration: String,
}

impl RunGeneration {
    /// The token identifying this process's run.
    ///
    /// Sixteen lower-case hexadecimal characters. Used to claim a one-shot action, to name a
    /// temporary file, to stamp an area report's generation preamble so that an earlier run's file
    /// cannot be aggregated into this run's totals, and to attribute a finding artifact to the run
    /// that produced it. Never written into a report's rendered Markdown or into a summary field, for
    /// the determinism reason the section comment above gives.
    pub fn token(&self) -> &str {
        &self.token
    }

    /// The fingerprint of the configuration this run was performed under.
    ///
    /// Deterministic: two runs configured alike produce the same value, and any difference in the
    /// effective matrix, the filters or the resolved tooling produces a different one. Safe to
    /// render into an artifact, because it introduces no dependence on the clock.
    pub fn configuration(&self) -> &str {
        &self.configuration
    }

    /// Record the configuration fingerprint, which may be set exactly once.
    ///
    /// The token is available before anything is known about the configuration — it has to be,
    /// since it names the temporary files the very first write uses — so the fingerprint is
    /// supplied by the first caller that holds a resolved configuration. Later callers agreeing
    /// with the recorded value are a no-op; a later caller *disagreeing* is a defect worth
    /// reporting, because two configurations in one process would put two runs' rows in one report.
    ///
    /// # Errors
    ///
    /// Returns an explanatory failure when a second, different fingerprint is offered.
    pub fn adopt_configuration(fingerprint: &str) -> HarnessResult<()> {
        let recorded = configuration_fingerprint();
        let mut held = recorded.lock().map_err(|_| {
            HarnessError::new(
                "recording the run's configuration fingerprint",
                "the fingerprint slot was poisoned by a panicking thread, so the identity of this \
                 run can no longer be established; a report assembled without it could mix two \
                 configurations",
            )
        })?;
        match held.as_deref() {
            None => {
                *held = Some(String::from(fingerprint));
                Ok(())
            }
            Some(existing) if existing == fingerprint => Ok(()),
            Some(existing) => Err(HarnessError::new(
                "recording the run's configuration fingerprint",
                format!(
                    "this process already recorded the configuration fingerprint \
                     {existing:?} and is now being offered {fingerprint:?}; one process is one \
                     run, and two configurations in it would let a summary count rows produced \
                     under different matrices as though they described the same run"
                ),
            )),
        }
    }
}

/// The slot the configuration fingerprint is recorded in, once per process.
fn configuration_fingerprint() -> &'static std::sync::Mutex<Option<String>> {
    static SLOT: OnceLock<std::sync::Mutex<Option<String>>> = OnceLock::new();
    SLOT.get_or_init(|| std::sync::Mutex::new(None))
}

/// This process's run generation, built once and shared by every caller.
///
/// The token is derived from the process identifier, the moment the first caller asked, and a
/// monotonic counter. All three are needed: the process identifier alone repeats across runs on a
/// long-lived machine, the clock alone repeats when two processes start inside one tick, and the
/// counter alone repeats on every run. Together they cannot collide between two live processes,
/// which is the only property required of them.
///
/// The configuration fingerprint reads whatever [`RunGeneration::adopt_configuration`] recorded, or
/// a documented placeholder when nothing has been recorded yet — which is the honest answer for an
/// artifact written before any configuration was resolved, and which a reader can act on.
pub fn run_generation() -> RunGeneration {
    static TOKEN: OnceLock<String> = OnceLock::new();
    static SEQUENCE: AtomicU64 = AtomicU64::new(0);
    let token = TOKEN.get_or_init(|| {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|since| since.as_nanos() as u64)
            .unwrap_or_default();
        let step = SEQUENCE.fetch_add(1, Ordering::Relaxed);
        let mixed = u64::from(std::process::id()).rotate_left(32) ^ nanos ^ step.rotate_left(17);
        format!("{mixed:016x}")
    });
    let configuration = match configuration_fingerprint().lock() {
        Ok(held) => held
            .clone()
            .unwrap_or_else(|| String::from("unresolved-configuration")),
        Err(_) => String::from("unresolved-configuration"),
    };
    RunGeneration {
        token: token.clone(),
        configuration,
    }
}

// =================================================================================================
// Symbolic-link-safe publication and removal
//
// Every path the suite writes is *predictable*: a workspace is named after its cell, a report after
// its feature area, a finding after its identity. Predictability is deliberate and is what makes a
// report row lead a maintainer straight to a directory — but it also means the name of a file this
// suite is about to create can be known in advance and replaced with a symbolic link pointing
// anywhere on the machine.
//
// A lexical containment check cannot see that: it reasons about the spelling of a path, and a link
// is a property of the filesystem. `std` offers no `O_NOFOLLOW`, and the project permits no crate
// that would, so the two primitives below establish the same guarantee from what `std` does offer:
//
// - the destination is inspected with [`fs::symlink_metadata`], which does not follow a final link,
//   and anything that is not an absent entry or a regular file is refused rather than written
//   through;
// - the bytes are written to a fresh sibling opened with `create_new`, which fails rather than
//   following or truncating an existing entry of any kind, and that sibling is then renamed onto
//   the destination. `rename` replaces the destination without following it, so the publication
//   itself cannot traverse a link either.
//
// The rename also makes every publication atomic, so a reader never observes a partially written
// artifact and a failed write leaves the previous complete one in place.
// =================================================================================================

/// How many distinct temporary names a publication will try before giving up.
///
/// A collision on the first name means another writer in this process is publishing the same
/// destination at the same instant, which the run generation and the counter already make
/// vanishingly unlikely; a handful of attempts covers a leftover file from a crashed run whose name
/// happens to match, and a bound keeps a genuinely undeletable directory from spinning forever.
const PUBLISH_ATTEMPTS: usize = 8;

/// Counter distinguishing the temporary names two concurrent publications choose.
static PUBLISH_SEQUENCE: AtomicU64 = AtomicU64::new(0);

/// Publish `bytes` at `path` without ever following a symbolic link, atomically.
///
/// Bytes rather than text throughout, because a captured standard output stream is compared byte
/// for byte and must be stored exactly as the program produced it.
///
/// # Errors
///
/// Returns an explanatory failure, attributed to `context`, when the destination has no parent,
/// when the destination exists and is not a regular file, when no temporary name could be created
/// exclusively, when the bytes could not be written or flushed, or when the rename failed. A
/// failure removes its own temporary file, so an error does not accumulate debris.
pub fn publish_bytes_no_follow(context: &str, path: &Path, bytes: &[u8]) -> HarnessResult<()> {
    stage_bytes_no_follow(context, path, bytes)?.commit()
}

/// A publication whose bytes are on disk but whose destination has not been claimed yet.
///
/// # Why staging is separable from committing
///
/// A single artifact never needs this: [`publish_bytes_no_follow`] stages and commits in one call.
/// A **pair** of artifacts does. The reports are emitted as a Markdown file and a machine-readable
/// sibling rendered from one snapshot, and publishing them as two independent operations leaves a
/// window in which a reader can consume a new Markdown summary beside the previous run's tab-separated
/// one — two files that disagree, each individually complete, with nothing to say they do not belong
/// together.
///
/// Splitting the two halves closes almost all of that window. Both files are written and flushed
/// first, so every way a write can fail has already happened; then the two renames follow one another
/// with no I/O between them. Two adjacent renames are not one atomic operation and this type does not
/// pretend otherwise — a directory-level swap would be needed for that, and it is not available
/// portably from `std` — but it reduces the exposure from "however long it takes to render and write a
/// second document" to the gap between two syscalls, and it removes every failure mode that could
/// leave the pair *permanently* mismatched.
///
/// # Cleanup is automatic
///
/// A staged publication that is dropped without being committed removes its own temporary file. That
/// is what makes staging safe to use in a fallible sequence: if the second of two stagings fails, the
/// first is discarded by unwinding out of scope and neither destination is touched.
#[must_use = "a staged publication that is never committed writes nothing and is discarded"]
pub struct StagedPublication {
    temporary: PathBuf,
    destination: PathBuf,
    context: String,
    committed: bool,
}

impl StagedPublication {
    /// Claim the destination by renaming the staged bytes onto it.
    ///
    /// # Errors
    ///
    /// Returns an explanatory failure, attributed to the staging context, when the rename fails. The
    /// previous artifact is left intact rather than replaced by a partial one.
    pub fn commit(mut self) -> HarnessResult<()> {
        if let Err(error) = fs::rename(&self.temporary, &self.destination) {
            return Err(HarnessError::new(
                self.context.clone(),
                format!(
                    "the temporary file {} could not be renamed onto {}: {error}; the previous \
                     artifact, if any, is left intact rather than replaced by a partial one",
                    self.temporary.display(),
                    self.destination.display()
                ),
            ));
        }
        self.committed = true;
        Ok(())
    }
}

impl Drop for StagedPublication {
    fn drop(&mut self) {
        if !self.committed {
            // Best effort by necessity: a destructor has nowhere to report to, and a leftover
            // temporary is a cosmetic problem where a panic in a destructor would be a fatal one.
            let _ = fs::remove_file(&self.temporary);
        }
    }
}

/// Write `bytes` to a freshly created sibling of `path`, without claiming `path` yet.
///
/// Every check and every failure mode of [`publish_bytes_no_follow`] happens here — the destination is
/// vetted, the temporary is created with `create_new` so it can never follow a planted link, and the
/// bytes are written and flushed. All that remains is the rename, which [`StagedPublication::commit`]
/// performs.
///
/// # Errors
///
/// Returns an explanatory failure, attributed to `context`, when the destination has no parent, when
/// the destination exists and is not a regular file, when no temporary name could be created
/// exclusively, or when the bytes could not be written or flushed.
pub fn stage_bytes_no_follow(
    context: &str,
    path: &Path,
    bytes: &[u8],
) -> HarnessResult<StagedPublication> {
    let parent = path.parent().ok_or_else(|| {
        HarnessError::new(
            String::from(context),
            format!(
                "{} has no parent directory, so it names no file that could be published",
                path.display()
            ),
        )
    })?;
    require_publishable_destination(context, path)?;

    let generation = run_generation();
    let mut last: Option<std::io::Error> = None;
    for _ in 0..PUBLISH_ATTEMPTS {
        let step = PUBLISH_SEQUENCE.fetch_add(1, Ordering::Relaxed);
        let stem = path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or("artifact");
        let temporary = parent.join(format!(
            ".{}.{}.{step:x}.tmp",
            keep_publishable_name(stem),
            generation.token()
        ));
        let handle = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temporary);
        let mut file = match handle {
            Ok(file) => file,
            Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {
                last = Some(error);
                continue;
            }
            Err(error) => {
                return Err(HarnessError::new(
                    String::from(context),
                    format!(
                        "the temporary file {} could not be created exclusively: {error}; every \
                         artifact is published by renaming a freshly created sibling, so that no \
                         write can follow a link planted at the destination",
                        temporary.display()
                    ),
                ));
            }
        };
        if let Err(error) = file.write_all(bytes).and_then(|()| file.flush()) {
            drop(file);
            let _ = fs::remove_file(&temporary);
            return Err(HarnessError::new(
                String::from(context),
                format!(
                    "{} could not be written through the temporary file {}: {error}",
                    path.display(),
                    temporary.display()
                ),
            ));
        }
        drop(file);
        return Ok(StagedPublication {
            temporary,
            destination: PathBuf::from(path),
            context: String::from(context),
            committed: false,
        });
    }

    Err(HarnessError::new(
        String::from(context),
        format!(
            "no exclusive temporary name for {} could be created in {PUBLISH_ATTEMPTS} attempts{}; \
             publication refuses to reuse an existing file, because reusing one is how a write \
             comes to follow a link somebody else placed",
            path.display(),
            match last {
                Some(error) => format!(" (last cause: {error})"),
                None => String::new(),
            }
        ),
    ))
}

// ---------------------------------------------------------------------------------------------
// Secure publication primitives
//
// Every artefact this suite writes lands at a *predictable* path, because a maintainer reading one
// row of a report must be able to open the directory it names without hunting for a randomized
// suffix. Predictability is the right trade here, but it has one consequence that must be closed
// rather than accepted: anything that can create a name before the suite does can decide where the
// write lands, and a plain `fs::write` follows a symbolic link at the leaf without complaint.
//
// The three functions below are the only way a byte leaves this suite, and they close that hole
// with two mechanisms and no third-party crate:
//
// - **Exclusive creation at the leaf.** `create_new` maps to `O_CREAT | O_EXCL`, and POSIX
//   requires `open` to fail with `EEXIST` when the final component is a symbolic link, *whatever*
//   the link points at. Measured directly: a pre-planted link at a workspace capture name is
//   refused and its target is left byte-identical. No `O_NOFOLLOW` constant and therefore no
//   `libc` dependency is needed, and no `unsafe` block appears anywhere.
// - **A verified real directory above it.** Exclusivity settles the leaf; it says nothing about
//   the directories on the way to it. [`require_real_directory`] and
//   [`require_directory_chain_below`] walk from a verified root down to the parent and require
//   every step to be a real directory rather than a link, so a redirected *parent* is refused too.
// ---------------------------------------------------------------------------------------------

/// Require that `path` is an existing directory and **not** a symbolic link to one.
///
/// [`std::fs::symlink_metadata`] is used deliberately: it does not follow a final link, so a link
/// is reported as a link and refused. Following it would let anything able to create that one name
/// decide where a whole subtree of artefacts is written while every report still showed the path
/// that was asked for.
pub fn require_real_directory(context: &str, path: &Path) -> HarnessResult<()> {
    let metadata = fs::symlink_metadata(path).map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!(
                "{} could not be inspected: {error}; every directory this suite writes beneath \
                 must exist and be a real directory before a byte is published into it",
                shown_path(path)
            ),
        )
    })?;
    let file_type = metadata.file_type();
    if file_type.is_symlink() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} is a symbolic link rather than a directory; it is refused instead of \
                 followed, because a link at this position would redirect every artefact written \
                 beneath it while each report still named this path",
                shown_path(path)
            ),
        ));
    }
    if !file_type.is_dir() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} exists but is not a directory, so nothing can be published inside it",
                shown_path(path)
            ),
        ));
    }
    Ok(())
}

/// The first *existing* level of `path` that is not a real directory, described, or `None`.
///
/// Walks from the filesystem root downwards and inspects every level of an absolute path with
/// [`fs::symlink_metadata`], stopping at the first component that does not exist yet. A level that
/// exists must be a real directory; a level that is a symbolic link, or that exists and is not a
/// directory, is reported. A path whose levels are all real directories, and a path whose existing
/// prefix is all real directories with the remainder simply absent, both answer `None`.
///
/// # Why the *whole* ancestry has to be walked, not just the leaf
///
/// Checking only the final component leaves the most useful attack completely unaddressed. The three
/// build roots are derived from one configurable directory, so a link planted at *any* level above
/// them relocates every workspace, every report and every finding this run publishes — and, worse,
/// relocates the ownership-aware purges those roots perform, so a destructive step aimed inside the
/// build tree would execute outside it. The leaf check would report nothing at all, because the leaf
/// itself is a perfectly ordinary directory sitting under a redirected parent.
///
/// A level that does not exist yet is accepted and ends the walk. That is the ordinary first-run
/// case — the build directory is created on demand — and the creating counterpart,
/// [`create_directory_chain_below`], re-verifies each level it creates, so the missing remainder is
/// established beneath a parent this walk has just confirmed.
///
/// The message is already report-safe: every path is rendered through [`shown_path`].
fn directory_ancestry_defect(path: &Path) -> Option<String> {
    if !path.is_absolute() {
        return Some(format!(
            "{} is not an absolute path, so the chain of directories above it cannot be identified, \
             let alone verified",
            shown_path(path)
        ));
    }
    let mut walked = PathBuf::new();
    for component in path.components() {
        match component {
            Component::Prefix(prefix) => walked.push(prefix.as_os_str()),
            Component::RootDir => walked.push(Component::RootDir.as_os_str()),
            Component::Normal(name) => walked.push(name),
            Component::CurDir | Component::ParentDir => {
                return Some(format!(
                    "{} contains a relative directory component, so the level it names cannot be \
                     verified without resolving it; it is refused instead",
                    shown_path(path)
                ));
            }
        }
        match fs::symlink_metadata(&walked) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Some(format!(
                    "{} is a symbolic link, and it is a level above {}; a link anywhere on this \
                     chain would redirect every artefact written beneath it — and every removal \
                     performed beneath it — while each report still named the path that was asked \
                     for, so it is refused rather than followed",
                    shown_path(&walked),
                    shown_path(path)
                ));
            }
            Ok(metadata) if !metadata.is_dir() => {
                return Some(format!(
                    "{} exists but is not a directory, and it is a level above {}, so nothing can \
                     be published beneath it",
                    shown_path(&walked),
                    shown_path(path)
                ));
            }
            Ok(_) => {}
            // The first absent level ends the walk: everything below it is absent too, and the
            // creating counterpart verifies each level as it establishes it.
            Err(error) if error.kind() == io::ErrorKind::NotFound => return None,
            Err(error) => {
                return Some(format!(
                    "{} could not be inspected: {error}; it is a level above {}, and a chain that \
                     cannot be verified is refused rather than assumed sound",
                    shown_path(&walked),
                    shown_path(path)
                ));
            }
        }
    }
    None
}

/// Require every existing level of the absolute path `path` to be a real directory.
///
/// The ancestry counterpart of [`require_real_directory`], which inspects one level. See
/// [`directory_ancestry_defect`] for why the whole chain has to be walked and why an absent level
/// ends the walk rather than failing it.
///
/// # Errors
///
/// Returns an explanatory failure naming the first existing level that is a symbolic link, is not a
/// directory, or could not be inspected — and naming the path whose ancestry was being verified, so
/// a reader learns both which level is wrong and what it was blocking.
pub fn require_real_directory_ancestry(context: &str, path: &Path) -> HarnessResult<()> {
    match directory_ancestry_defect(path) {
        None => Ok(()),
        Some(defect) => Err(HarnessError::new(String::from(context), defect)),
    }
}

/// Require that every directory from `root` down to `directory` inclusive is a real directory.
///
/// `root` must already have been established — it is one of the three build roots — and is
/// verified here as well, because a check that is cheap and unconditional cannot be forgotten
/// during maintenance. `directory` must lie beneath `root` lexically; a component that is not a
/// plain name is refused rather than resolved, so the walk can never climb out of the root.
///
/// # Errors
///
/// Returns an explanatory failure naming the first step that is absent, is a symbolic link, or is
/// not a directory.
pub fn require_directory_chain_below(
    context: &str,
    root: &Path,
    directory: &Path,
) -> HarnessResult<()> {
    require_real_directory(context, root)?;
    let mut remaining = directory.components();
    for expected in root.components() {
        if remaining.next() != Some(expected) {
            return Err(HarnessError::new(
                String::from(context),
                format!(
                    "{} does not lie beneath {}, so the chain of directories above it cannot be \
                     verified and nothing is published into it",
                    shown_path(directory),
                    shown_path(root)
                ),
            ));
        }
    }
    let mut walked = PathBuf::from(root);
    for component in remaining {
        match component {
            Component::Normal(name) => {
                walked.push(name);
                require_real_directory(context, &walked)?;
            }
            _ => {
                return Err(HarnessError::new(
                    String::from(context),
                    format!(
                        "{} contains a component that is not a plain name below {}; a \
                         parent-directory or root component would let the path climb out of the \
                         build directory, so it is refused instead of resolved",
                        shown_path(directory),
                        shown_path(root)
                    ),
                ));
            }
        }
    }
    Ok(())
}

/// Create `directory`, and every missing level between `root` and it, one level at a time.
///
/// Deliberately **not** [`fs::create_dir_all`] for the levels below `root`. That call follows a
/// symbolic link at any level and reports success, so one planted link on the way down would place a
/// whole subtree of artefacts wherever the link pointed while every report still named the path that
/// was asked for. Every path this suite publishes is derived deterministically, so its name is
/// predictable before the run that will use it — which is exactly the precondition such a link needs.
///
/// This walks instead: each level below the verified root is created if absent and then required to
/// be a real directory by [`require_real_directory`], which inspects it without following a final
/// link. The walk therefore refuses **at** the offending level and creates nothing beyond it.
///
/// An already-present level is not an error. Concurrent feature areas create the same parents, and a
/// republished directory is expected to be there already.
///
/// `root` itself is attempted with [`fs::create_dir_all`] and then verified by the same
/// real-directory check as every level below it, so a link *at* the root is refused just as one below
/// it is. It is attempted rather than required to exist because the roots are established once by the
/// driver, and losing an artefact to an absent parent directory would report a real result as a
/// harness failure — which is worse than either.
///
/// The root's own **ancestry is verified first**, by [`require_real_directory_ancestry`], because
/// `fs::create_dir_all` follows a symbolic link at any level and reports success. Verifying only the
/// root after the fact would accept a root that had been created *through* a redirected parent, which
/// is the one arrangement this walk exists to refuse — and it must be refused here rather than left
/// to [`build_root`], because a caller may pass any root and the guarantee has to hold for whichever
/// one it passes.
///
/// The creating counterpart of [`require_directory_chain_below`], and the single implementation of
/// this walk: `findings.rs` and `report.rs` both publish into deterministically named directories
/// beneath a root, and a second copy of the walk is a second chance to get one level wrong.
///
/// # Errors
///
/// Returns an explanatory failure when `directory` does not lie beneath `root`, when it carries a
/// component that is not a plain name, when a level cannot be created, or when a level is present
/// but is a symbolic link or not a directory.
pub fn create_directory_chain_below(
    context: &str,
    root: &Path,
    directory: &Path,
) -> HarnessResult<()> {
    // Before the creation, never after it: `fs::create_dir_all` follows a symbolic link at any level
    // and reports success, so a root created through a redirected parent would pass the
    // real-directory check below while sitting entirely outside the build tree.
    require_real_directory_ancestry(context, root)?;
    // Normally a no-op: the driver establishes the three build roots before any area begins. The
    // outcome is deliberately ignored in favour of the verification on the next line, which is what
    // actually decides whether publication may proceed.
    let _ = fs::create_dir_all(root);
    require_real_directory(context, root)?;

    let mut remaining = directory.components();
    for expected in root.components() {
        if remaining.next() != Some(expected) {
            return Err(HarnessError::new(
                String::from(context),
                format!(
                    "{} does not lie beneath {}, so the directories above it cannot be created under \
                     verification and nothing is published into it",
                    shown_path(directory),
                    shown_path(root)
                ),
            ));
        }
    }

    let mut walked = PathBuf::from(root);
    for component in remaining {
        let Component::Normal(name) = component else {
            return Err(HarnessError::new(
                String::from(context),
                format!(
                    "{} contains a component that is not a plain name below {}; a parent-directory \
                     or root component would let the path climb out of the build directory, so it is \
                     refused instead of resolved",
                    shown_path(directory),
                    shown_path(root)
                ),
            ));
        };
        walked.push(name);
        match fs::create_dir(&walked) {
            Ok(()) => {}
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => {}
            Err(error) => {
                return Err(HarnessError::new(
                    String::from(context),
                    format!(
                        "{} could not be created: {error}; every artefact this suite produces is \
                         written beneath the build directory, so a directory that cannot be created \
                         stops the artefact from being written rather than diverting it elsewhere",
                        shown_path(&walked)
                    ),
                ));
            }
        }
        require_real_directory(context, &walked)?;
    }
    Ok(())
}

/// Require that `path` is either absent or a regular file, without following a final link.
///
/// The one condition publication needs: a rename may replace an absent entry or a regular file
/// safely, while a directory, a device node, a socket, a FIFO or a **symbolic link** at the
/// destination each mean the suite is about to write somewhere it did not choose.
pub fn require_publishable_destination(context: &str, path: &Path) -> HarnessResult<()> {
    match fs::symlink_metadata(path) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(HarnessError::new(
            String::from(context),
            format!(
                "{} could not be inspected before publication: {error}; an artifact is only ever \
                 written over an entry the suite has established is a plain file",
                path.display()
            ),
        )),
        Ok(metadata) if metadata.file_type().is_symlink() => Err(HarnessError::new(
            String::from(context),
            format!(
                "{} is a symbolic link; publication refuses to follow one, because the link's \
                 target may lie anywhere on the machine while every report still names the path \
                 that was asked for",
                path.display()
            ),
        )),
        Ok(metadata) if metadata.file_type().is_file() => Ok(()),
        Ok(_) => Err(HarnessError::new(
            String::from(context),
            format!(
                "{} exists and is not a regular file, so it cannot be replaced by one; a \
                 directory, device node, socket or FIFO at an artifact's path is a condition to \
                 report rather than to write through",
                path.display()
            ),
        )),
    }
}

/// Create `path` exclusively and return the open handle, refusing anything already there.
///
/// The single publication primitive of this suite. `create_new` is `O_CREAT | O_EXCL`, which
/// POSIX requires to fail with `EEXIST` when the final component names a symbolic link — so a
/// pre-planted link cannot redirect the write, and neither can a pre-planted regular file, device
/// node or FIFO. The handle is then re-inspected through itself rather than through the path
/// again: the object must be a regular file with exactly one link, which proves the suite is
/// writing to something it created rather than to a hard link into another file.
///
/// Callers that legitimately republish a path — a report rewritten on a second run, a finding
/// directory re-derived from the same divergence — remove the previous entry first through a
/// guarded removal and then create it here. Replacing in place is deliberately not offered,
/// because "truncate whatever is at this name" is exactly the operation a link exploits.
///
/// # Errors
///
/// Returns an explanatory failure when the entry already exists, when it cannot be created, or
/// when the created object is not a fresh regular file.
pub fn create_new_file(context: &str, path: &Path) -> HarnessResult<File> {
    let file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
        .map_err(|error| {
            HarnessError::new(
                String::from(context),
                format!(
                    "{} could not be created exclusively: {error}. The suite creates every \
                     artefact with O_CREAT|O_EXCL, which refuses a name that already exists — \
                     including a symbolic link, whatever it points at — so an entry already at \
                     this path is refused rather than written through. Remove the stale entry, or \
                     investigate what created it",
                    shown_path(path)
                ),
            )
        })?;
    let metadata = file.metadata().map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!(
                "{} was created but could not be inspected through its own handle: {error}",
                shown_path(path)
            ),
        )
    })?;
    if !metadata.is_file() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} was created but is not a regular file, so it is refused rather than written to",
                shown_path(path)
            ),
        ));
    }
    if hard_link_count(&metadata).is_some_and(|links| links != 1) {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} was created but already carries more than one hard link, so writing to it \
                 would write into another file as well; it is refused rather than used",
                shown_path(path)
            ),
        ));
    }
    Ok(file)
}

/// Number of hard links to a file, where the platform exposes it.
#[cfg(unix)]
fn hard_link_count(metadata: &fs::Metadata) -> Option<u64> {
    use std::os::unix::fs::MetadataExt;
    Some(metadata.nlink())
}

/// Fallback for a platform with no hard-link notion, where the question cannot be asked.
#[cfg(not(unix))]
fn hard_link_count(_metadata: &fs::Metadata) -> Option<u64> {
    None
}

/// Create `path` exclusively and write `bytes` into it.
///
/// Bytes rather than text everywhere, because a captured standard output stream is compared byte
/// for byte and must be stored exactly as the program produced it — no line-ending
/// normalization, and no replacement character for a byte that is not valid text.
///
/// # Errors
///
/// Everything [`create_new_file`] can fail on, plus a failed write.
pub fn write_new_file(context: &str, path: &Path, bytes: &[u8]) -> HarnessResult<()> {
    use std::io::Write;
    let mut file = create_new_file(context, path)?;
    file.write_all(bytes).map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!("{} could not be written: {error}", shown_path(path)),
        )
    })?;
    file.sync_all().map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!("{} could not be flushed to disk: {error}", shown_path(path)),
        )
    })
}

/// Remove whatever is at `path`, treating absence as success and never following a link.
///
/// The counterpart of [`create_new_file`], and the "guarded removal" its documentation refers to.
/// Exclusive creation refuses to publish over an existing name, which is exactly right, but a
/// caller that legitimately republishes — a report rewritten on a second run, a finding directory
/// re-derived from the same divergence — needs a way to clear the old name first. Doing that with a
/// truncating write is what the exclusivity was protecting against; doing it here is safe, and for
/// one specific reason:
///
/// - a symbolic link is inspected with [`std::fs::symlink_metadata`] and removed **as a link**, so
///   a link planted at the name is deleted and whatever it pointed at is left byte-identical. A
///   recursive removal aimed at a link would either fail or, on a platform that followed it, delete
///   the contents of its target — which is the whole hazard, inverted;
/// - anything that is not a directory is removed as a single entry, so a stale plain file, device
///   node or FIFO left where a directory belongs cannot block the run;
/// - a real directory is removed with its contents, which is what makes republication idempotent.
///
/// Containment is deliberately **not** checked here. Each caller bounds a removal by its own root —
/// the work root, the report root, the findings root — and applies that check before calling, which
/// keeps the rule about where a module may delete beside the module it governs. The decision this
/// function centralises is the one that is easy to get subtly wrong, and getting it wrong in one of
/// three copies is how the wrong one survives review.
///
/// # Errors
///
/// Returns an explanatory failure naming the path when it cannot be inspected for a reason other
/// than absence, or when the removal itself fails.
pub fn remove_entry(context: &str, path: &Path) -> HarnessResult<()> {
    let metadata = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(()),
        Err(error) => {
            return Err(HarnessError::new(
                String::from(context),
                format!(
                    "{} could not be inspected before removal: {error}",
                    shown_path(path)
                ),
            ));
        }
    };

    let file_type = metadata.file_type();
    let removal = if file_type.is_symlink() || !file_type.is_dir() {
        fs::remove_file(path)
    } else {
        fs::remove_dir_all(path)
    };
    removal.map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!("{} could not be removed: {error}", shown_path(path)),
        )
    })
}

/// Require that a directory the suite created is a real directory beneath `root`, and return its
/// resolved path.
///
/// The companion to a lexical containment check, and the half that cannot be forged. A lexical
/// check proves the *spelling* of a path stays inside a root; this resolves the directory that now
/// exists and proves the *filesystem* agrees, which is the only way to detect that the name was a
/// symbolic link out of the build tree all along.
///
/// # Errors
///
/// Fails when the entry is absent, is a symbolic link, is not a directory, or does not resolve
/// strictly beneath `root`.
pub fn require_real_directory_within(
    context: &str,
    root: &Path,
    path: &Path,
) -> HarnessResult<PathBuf> {
    let metadata = fs::symlink_metadata(path).map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!(
                "{} could not be inspected: {error}; the suite writes only into directories it has \
                 established exist beneath the build directory",
                path.display()
            ),
        )
    })?;
    let file_type = metadata.file_type();
    if file_type.is_symlink() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} is a symbolic link rather than a directory; following it would place every \
                 artifact of this run wherever the link points while each report still named this \
                 path",
                path.display()
            ),
        ));
    }
    if !file_type.is_dir() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} exists and is not a directory, so nothing can be written inside it",
                path.display()
            ),
        ));
    }
    ensure_within(context, root, path)
}
/// The one kind of object that may legitimately already occupy a path this suite publishes.
///
/// Republication is documented behaviour throughout the suite — a report is rewritten on every run,
/// and the same divergence derives the same finding directory — so "something is already here" cannot
/// simply be refused. But the only thing that can legitimately be here is the same *kind* of object
/// the suite writes at that name: a regular file at an artefact name, a real directory at a directory
/// name. Anything else was put there by something other than this suite.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Replaceable {
    /// An artefact leaf: a regular file, and nothing else.
    RegularFile,
    /// A published directory: a real directory, and nothing else.
    Directory,
}

impl Replaceable {
    /// The phrase naming what the suite writes at such a path.
    fn description(self) -> &'static str {
        match self {
            Replaceable::RegularFile => "a regular file",
            Replaceable::Directory => "a directory",
        }
    }

    /// Whether `file_type` is that kind. A symbolic link is judged separately and never accepted.
    fn accepts(self, file_type: fs::FileType) -> bool {
        match self {
            Replaceable::RegularFile => file_type.is_file(),
            Replaceable::Directory => file_type.is_dir(),
        }
    }
}

/// Refuse a publication path already occupied by something this suite did not write.
///
/// Absence is success — that is the ordinary case. A pre-existing object of the expected kind is also
/// success, because republishing a report or a finding is documented behaviour and the caller replaces
/// it through a guarded removal ([`remove_entry`]) followed by an exclusive create
/// ([`create_new_file`]).
///
/// A **symbolic link** is refused rather than replaced, and the distinction is deliberate. Removing it
/// would be safe in itself — [`remove_entry`] unlinks a link as a link and leaves its target
/// byte-identical — but the suite never creates a link at any of these names, so one being here means
/// something else did, and repairing that silently would discard the only evidence that it happened. A
/// refusal is a loud, attributable failure carrying the path; a silent repair is an artefact published
/// as though nothing were wrong.
///
/// Anything else that is not the expected kind — a directory where a file belongs, a FIFO, a device
/// node, a socket — is refused for the same reason.
///
/// Shared rather than reimplemented per module: this is one judgement, made in one place, for every
/// path the suite publishes.
///
/// # Errors
///
/// Returns an explanatory failure naming the path when it cannot be inspected for a reason other than
/// absence, when it is a symbolic link, or when it is not `kind`.
pub fn require_replaceable(context: &str, path: &Path, kind: Replaceable) -> HarnessResult<()> {
    let metadata = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(()),
        Err(error) => {
            return Err(HarnessError::new(
                String::from(context),
                format!(
                    "{} could not be inspected before it was published: {error}",
                    shown_path(path)
                ),
            ));
        }
    };
    let file_type = metadata.file_type();
    if file_type.is_symlink() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} is a symbolic link. The suite publishes {} at that name and never a link, so a \
                 link being there means something outside this suite created it — and following it \
                 would write the artefact through it, while removing it would hide that it had been \
                 done. It is refused instead, and the run fails loudly rather than publishing as \
                 though nothing were wrong",
                shown_path(path),
                kind.description()
            ),
        ));
    }
    if !kind.accepts(file_type) {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} already exists and is not {}, which is what the suite publishes there; it is \
                 refused rather than replaced, because nothing this suite wrote could have put a \
                 different kind of object at that name",
                shown_path(path),
                kind.description()
            ),
        ));
    }
    Ok(())
}

/// Upper bound on any single file this suite reads back for inspection.
///
/// Sixteen mebibytes is orders of magnitude above every artefact the suite produces — a
/// statically linked single-function probe program is a couple of megabytes at most, and an area
/// report is kilobytes — and low enough that an oversized or hostile file is refused rather than
/// resident. The bound exists because an unbounded read of an attacker-chosen path is a denial of
/// service with no compensating benefit: nothing the suite decides needs more bytes than this.
pub const MAX_INSPECTED_FILE_BYTES: u64 = 16 * 1024 * 1024;

/// Open `path` as a regular file, refusing a link or a special file, and prove the **opened handle**
/// is the entry that was inspected.
///
/// Returns the handle and the metadata read *from that handle*, so a caller sizes its buffer and
/// bounds its read from the object it is actually holding rather than from a name that may since have
/// been re-pointed.
///
/// # The window this closes, and why the inspection alone does not close it
///
/// Inspecting a name and then opening it are two operations on a *name*, and every path this suite
/// reads is deterministic — a workspace is named after its cell, a report after its area, a finding
/// after its identity — so the name is predictable before the run that will use it. Between the
/// inspection and the open, that name can be replaced by a symbolic link to anywhere on the machine.
/// The inspection would report a perfectly ordinary regular file and the open would read the link's
/// target, while every diagnostic still named the path that was asked for. Nothing in the two-call
/// sequence can detect that.
///
/// So the identity is compared **after** the open, from the handle itself:
///
/// - the handle's own metadata must still describe a regular file, which is the check that cannot be
///   raced at all, because it interrogates the object rather than the name;
/// - on a platform that exposes them, the handle's device and inode numbers must equal the ones read
///   before the open. They see through every spelling, so a replacement is caught whatever it was
///   replaced with;
/// - where they are not exposed, the regular-file check on the handle stands alone and the two
///   answers are never mixed, so an absent identity cannot be mistaken for a match.
///
/// This does not make the sequence atomic — the standard library offers no way to open a path with
/// `O_NOFOLLOW`, and no `unsafe` block or `libc` dependency is permitted here. What it does is convert
/// a silent substitution into a named refusal, which is the achievable property.
fn open_verified_regular_file(
    context: &str,
    path: &Path,
) -> HarnessResult<(File, std::fs::Metadata)> {
    let before = fs::symlink_metadata(path).map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!("{} could not be inspected: {error}", shown_path(path)),
        )
    })?;
    let file_type = before.file_type();
    if file_type.is_symlink() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} is a symbolic link; it is refused rather than followed, because following one \
                 would read a file from anywhere on the machine while every report still showed \
                 this path",
                shown_path(path)
            ),
        ));
    }
    if !file_type.is_file() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} is not a regular file; reading a directory, device node, socket or FIFO can \
                 block without end, so it is refused",
                shown_path(path)
            ),
        ));
    }

    let file = File::open(path).map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!("{} could not be opened: {error}", shown_path(path)),
        )
    })?;
    let opened = file.metadata().map_err(|error| {
        HarnessError::new(
            String::from(context),
            format!(
                "{} was opened but the open file could not be inspected: {error}; without that \
                 answer there is no way to show the handle describes the entry that was vetted, so \
                 nothing is read from it",
                shown_path(path)
            ),
        )
    })?;
    if !opened.file_type().is_file() {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} was a regular file when it was inspected and the opened handle is not one, so \
                 the entry was replaced between the two; nothing is read from it",
                shown_path(path)
            ),
        ));
    }
    if let (Some(vetted), Some(held)) = (identity_of(&before), identity_of(&opened)) {
        if vetted != held {
            return Err(HarnessError::new(
                String::from(context),
                format!(
                    "{} is not the file that was inspected: it was device {} inode {} and the \
                     opened handle is device {} inode {}, so the name was re-pointed between the \
                     inspection and the open. Nothing is read from it, because bytes this suite \
                     cannot attribute to a known file are not evidence",
                    shown_path(path),
                    vetted.0,
                    vetted.1,
                    held.0,
                    held.1
                ),
            ));
        }
    }
    Ok((file, opened))
}

/// The device and inode numbers of an entry, where the platform exposes them.
///
/// `None` on a platform that does not, which every caller must treat as "no answer" rather than as a
/// match: mixing the two would let an absent identity read as an established one.
fn identity_of(metadata: &std::fs::Metadata) -> Option<(u64, u64)> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        Some((metadata.dev(), metadata.ino()))
    }
    #[cfg(not(unix))]
    {
        let _ = metadata;
        None
    }
}

/// Read the whole of a regular file, refusing a link, a special file or an oversized one.
///
/// Four properties hold together, and each closes a distinct hazard:
///
/// - the entry is inspected with [`std::fs::symlink_metadata`], so a symbolic link is refused
///   rather than followed and a device node or FIFO — which can block without end — is refused
///   rather than read;
/// - the **opened handle** is proved to be the entry that was inspected, by
///   [`open_verified_regular_file`], so a name re-pointed between the inspection and the open is a
///   named refusal rather than a silent read of somewhere else;
/// - the length reported by that handle is compared against `limit` **before** any byte is read, so
///   an oversized file costs one metadata call rather than its own size in memory;
/// - the read itself takes `limit + 1` bytes and **refuses** the result when more than `limit`
///   arrive. Taking exactly `limit` would return a prefix and call it the file: a file that grew
///   after its length was read would be silently truncated, and a truncated artefact compared
///   against a whole one is reported as a divergence in the compiler.
///
/// # Errors
///
/// Returns an explanatory failure naming the path for each of the conditions above and for an
/// unreadable file.
pub fn read_file_bounded(context: &str, path: &Path, limit: u64) -> HarnessResult<Vec<u8>> {
    let (file, metadata) = open_verified_regular_file(context, path)?;
    if metadata.len() > limit {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} is {} bytes, which exceeds the {limit}-byte ceiling this suite reads; an \
                 artefact that large is refused rather than held in memory, because nothing the \
                 suite decides needs more bytes than that",
                shown_path(path),
                metadata.len()
            ),
        ));
    }

    let mut bytes = Vec::with_capacity(usize::try_from(metadata.len()).unwrap_or_default());
    // One byte past the ceiling, so that overflow is *observed* rather than silently cut off.
    file.take(limit.saturating_add(1))
        .read_to_end(&mut bytes)
        .map_err(|error| {
            HarnessError::new(
                String::from(context),
                format!("{} could not be read: {error}", shown_path(path)),
            )
        })?;
    if bytes.len() as u64 > limit {
        return Err(HarnessError::new(
            String::from(context),
            format!(
                "{} grew past the {limit}-byte ceiling while it was being read, so what was \
                 collected is a prefix rather than the file; it is refused instead of returned, \
                 because a truncated artefact compared against a whole one would be reported as a \
                 divergence in the compiler",
                shown_path(path)
            ),
        ));
    }
    Ok(bytes)
}

/// `raw` with every character that cannot appear in a temporary file name replaced.
///
/// Applied only to the stem of a temporary name, which is never published and never printed, so the
/// mapping needs to be safe rather than injective: two destinations that reduced to the same stem
/// are still distinguished by the run token and the counter that follow it.
fn keep_publishable_name(raw: &str) -> String {
    raw.chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '.' || character == '-' {
                character
            } else {
                '_'
            }
        })
        .collect()
}

// =================================================================================================
// Capture integrity
//
// Every subprocess this suite starts has both of its output streams drained on their own threads,
// and two facts about that drain have to travel with the bytes rather than be assumed:
//
// - **How much was retained against how much was produced.** A buffer that grows without a bound
//   is a memory fault waiting for a compiler that prints without end, and 1,296 cells run
//   concurrently. So a quota applies. But a quota that silently discarded the overflow would be
//   worse than no quota at all, because the truncated bytes are the ones under byte-exact
//   comparison.
// - **Whether the reader finished.** Terminating a child does not close the pipe it wrote to: any
//   process that inherited the write end still holds it open, so a drain has to be bounded too,
//   and a drain that gave up has not observed the whole stream.
//
// Both facts are carried in one value, so that no consumer can read the bytes without also being
// able to ask how faithful they are — which is what lets a comparison refuse a truncated stdout
// and a classifier refuse to attribute a failure to a compiler on the strength of diagnostics it
// never fully read.
// =================================================================================================

/// Bytes retained from one captured stream before the remainder is drained and discarded.
///
/// Generous by four orders of magnitude against what any corpus program or compiler invocation
/// legitimately produces: a program prints one line per property it asserts, and a diagnostic
/// listing runs to kilobytes. Reaching this bound therefore means something is wrong, which is why
/// the overflow is disclosed rather than absorbed.
pub const CAPTURE_RETAINED_BYTES_MAX: u64 = 4 * 1024 * 1024;

/// Bytes one reader asks a pipe for at a time.
///
/// Shared by both drain implementations — the one that collects a program's output and the one
/// that collects a compiler's diagnostics — because the granularity is what makes the produced
/// count exact: each read reports its own length, so the total is a sum of measured reads rather
/// than an inference from how much was retained. Sized well above a pipe's kernel buffer, so a
/// stream is emptied in few syscalls, and well below the retention quota, so the quota is reached
/// on a chunk boundary rather than in one enormous allocation.
pub const CAPTURE_CHUNK_BYTES: usize = 16 * 1024;

/// How faithfully one captured stream represents what the child actually wrote.
///
/// Deliberately a value rather than a pair of loose booleans on each outcome type: the four facts
/// are only meaningful together — 4 MiB retained out of 4 MiB produced with the reader finished is
/// a complete capture, while the same 4 MiB out of 40 MiB is a quarter of a diagnostic listing —
/// and a consumer that received them separately could pass on three of them and drop the fourth.
///
/// The fields are private because the value is an observation. A caller able to clear
/// [`CaptureIntegrity::truncated`] could turn a partial standard output into one that is compared
/// byte for byte as though it were whole, which would be reported as a divergence in the compiler
/// under test — the one failure mode that would leave no trace of its real cause.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct CaptureIntegrity {
    produced: u64,
    retained: u64,
    truncated: bool,
    drained: bool,
}

impl CaptureIntegrity {
    /// Record what one drained stream produced, retained, and whether its reader finished.
    ///
    /// `truncated` is supplied rather than derived from the two counts, because the counts alone
    /// cannot distinguish the two cases that matter: a reader that was abandoned at a deadline
    /// retained everything it had *received* and is not truncated by the quota, while a reader that
    /// hit the quota is. Both are incomplete, and a report has to be able to say which.
    pub fn new(produced: u64, retained: u64, truncated: bool, drained: bool) -> CaptureIntegrity {
        CaptureIntegrity {
            produced,
            retained,
            truncated,
            drained,
        }
    }

    /// Bytes the child wrote into the pipe, including any the quota discarded.
    /// Bytes kept, which is what a comparison and a report artifact actually hold.
    /// Whether the quota discarded part of the stream.
    pub fn truncated(self) -> bool {
        self.truncated
    }

    /// Whether the reader reached the end of the stream rather than being abandoned at a deadline.
    pub fn drained(self) -> bool {
        self.drained
    }

    /// Whether the retained bytes are the whole stream.
    ///
    /// The single predicate every consumer wants: a complete capture may be compared byte for byte
    /// and may be interpreted to decide who is answerable for a failure, and an incomplete one may
    /// be neither without saying so.
    pub fn complete(self) -> bool {
        self.drained && !self.truncated
    }

    /// One clause naming this stream's fidelity, for a one-line description.
    ///
    /// Silent — an empty string — for a complete capture, so an ordinary description carries no
    /// noise and a description that does carry a clause is worth reading.
    pub fn describe(self, role: &str) -> String {
        if self.complete() {
            return String::new();
        }
        let mut clause = format!("; {role} capture is INCOMPLETE");
        if self.truncated {
            clause.push_str(&format!(
                " (retained {} of {} byte(s) produced; the {CAPTURE_RETAINED_BYTES_MAX}-byte quota \
                 discarded the remainder)",
                self.retained, self.produced
            ));
        }
        if !self.drained {
            clause.push_str(
                " (the reader was still blocked when its deadline expired, so a process that \
                 inherited the pipe is holding it open and the stream may be short of what was \
                 written)",
            );
        }
        clause
    }

    /// The `key = value` lines this stream contributes to a workspace status record.
    ///
    /// Written for every capture, complete or not, because a record that mentioned fidelity only
    /// when it was poor would leave a reader unable to tell a complete capture from an older record
    /// that predated the accounting.
    pub fn record_lines(self, role: &str) -> String {
        format!(
            "{role}_produced_bytes = {}\n{role}_retained_bytes = {}\n{role}_truncated = {}\n\
             {role}_drained = {}\n{role}_capture_complete = {}\n",
            self.produced,
            self.retained,
            self.truncated,
            self.drained,
            self.complete()
        )
    }
}
/// A filesystem path rendered safely for a report line, a diagnostic or a summary.
///
/// The single authority for turning a path into text anywhere in this suite. A path is not
/// trusted input: it can carry a byte from an environment variable, from a discovered tool
/// location or from a corpus entry, and rendering it with [`std::path::Display`] verbatim would
/// let a control character, an escape introducer or a directional override forge a column, erase
/// a line or make a verdict render as its opposite. Everything goes through
/// [`sanitize_text_for_report`], which escapes exactly those characters and leaves ordinary text
/// — including legitimate non-ASCII — untouched.
///
/// A path that is not valid text is rendered lossily *for the diagnostic only*: every path the
/// suite actually compiles, executes or publishes is proved to be valid text before it is used,
/// so a lossy rendering can only ever appear in the message explaining that refusal.
pub fn shown_path(path: &Path) -> String {
    sanitize_text_for_report(&path.to_string_lossy())
}

// ---------------------------------------------------------------------------------------------
// Rendering untrusted text into Markdown
//
// The reports are Markdown, and some of the text in them comes from outside this suite: a
// maintainer's prose in an expectation record, a compiler's diagnostic, a tool's own banner, a
// discovered path. [`sanitize_text_for_report`] makes such text safe to put on a *line* — it can
// no longer forge a column or repaint a terminal — but it deliberately leaves printable
// characters alone, and in Markdown several printable characters are syntax. A permissive
// renderer will honour raw HTML, and a link or emphasis introducer can restructure a document.
//
// The two functions below are therefore applied *in addition* to sanitization, at the Markdown
// sinks only. The machine-readable tab-separated sibling is left unescaped on purpose: it is data
// for an aggregator rather than a document, escaping would corrupt the values an external tool
// reads, and sanitization has already removed everything that could break its row-and-column
// structure.
// ---------------------------------------------------------------------------------------------

/// `raw` with the five characters that begin HTML markup replaced by their entities.
///
/// Applied to every piece of untrusted text that reaches a Markdown artefact, because Markdown
/// renderers commonly pass raw HTML through: a recorded reason containing a script element or an
/// image with an event handler would otherwise become active content in a rendered report.
/// Escaping is done in one pass with the ampersand handled first, so no substitution can be
/// re-interpreted by a later one.
pub fn escape_html_text(raw: &str) -> String {
    let mut safe = String::with_capacity(raw.len());
    for character in raw.chars() {
        match character {
            '&' => safe.push_str("&amp;"),
            '<' => safe.push_str("&lt;"),
            '>' => safe.push_str("&gt;"),
            '"' => safe.push_str("&quot;"),
            '\'' => safe.push_str("&#39;"),
            other => safe.push(other),
        }
    }
    safe
}

/// The Markdown characters that are syntax in inline position and are therefore escaped.
///
/// The backslash comes first because it is the escape character itself: escaping it last would
/// double every escape this function had already inserted. The vertical bar is included so that
/// untrusted text can never end a table cell and shift every value after it into the wrong
/// column — the table equivalent of forging a tab-separated field.
const MARKDOWN_INLINE_SYNTAX: &[char] = &[
    '\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '!', '|', '{', '}', '~',
];

/// `raw` rendered so that a Markdown reader shows it literally and acts on none of it.
///
/// Composed of the two halves that are each insufficient alone: [`escape_html_text`] neutralizes
/// raw HTML, and a backslash escape in front of each member of [`MARKDOWN_INLINE_SYNTAX`]
/// neutralizes links, emphasis, code spans, headings, list markers and table separators. The
/// caller is expected to have sanitized control characters already — this function is about
/// document structure, not about terminal safety — and the two are always applied together at the
/// sinks in `report.rs`.
pub fn escape_markdown_inline(raw: &str) -> String {
    let html_safe = escape_html_text(raw);
    let mut safe = String::with_capacity(html_safe.len());
    for character in html_safe.chars() {
        if MARKDOWN_INLINE_SYNTAX.contains(&character) {
            safe.push('\\');
        }
        safe.push(character);
    }
    safe
}

// ---------------------------------------------------------------------------------------------
// Child-process isolation
//
// This suite spawns programs it does not control: two compilers, three emulators, an optional
// timeout utility, and the artefacts those compilers produce. Every one of them inherits the
// environment of the test process by default, and in continuous integration that environment
// holds credentials. Two distinct failures follow from inheriting it, and both are closed here
// rather than at each of the nine spawn sites:
//
// - **A secret reaches a program the suite does not control**, which can print it; the harness
//   then captures that output and writes it into a report and into a finding's environment
//   fingerprint, where it is committed as a deliverable.
// - **A variable changes what the child does.** The sanitizer runtimes read `ASAN_OPTIONS`,
//   `UBSAN_OPTIONS` and `LSAN_OPTIONS`; an inherited `ASAN_OPTIONS=detect_leaks=0:halt_on_error=0`
//   is enough to turn a program with undefined behaviour into a clean audit pass, which would
//   silently remove the precondition that makes every divergence in this suite meaningful. The
//   dynamic loader reads `LD_PRELOAD` and `LD_LIBRARY_PATH`; a compiler driver reads a dozen
//   `*_INCLUDE_PATH` and `*_OPTIONS` variables that change the language it accepts.
// - **A variable decides which program the child executes.** `PATH` is the case that matters, and
//   it is the one variable a child genuinely needs, so it cannot simply be dropped: a compiler
//   driver finds its own stages through it. It is therefore rebuilt from the vetted entries rather
//   than inherited, because a driver handed the raw value would search directories that tool
//   resolution had already refused — substituting a stage instead of the driver, one level below
//   where the filter looked.
//
// The response is the same in every case and is not negotiable per call site: clear the
// environment and put back a small, documented, entirely suite-chosen set, in which even `PATH` is
// a suite-computed value rather than an inherited one.
// ---------------------------------------------------------------------------------------------

/// `PATH` is the one variable a child needs from outside this file, and it is **not inherited**.
///
/// A child does need a search path: a compiler driver locates its own stages — `cc1`, `as`, `ld`,
/// `collect2` — through it, and clearing it entirely makes every reference-compiler invocation fail
/// with "cannot execute `cc1`". What it must not receive is the *inherited* value.
///
/// [`env::sanitized_search_path`] supplies the trustworthy entries and nothing else — the same
/// accepted list tool resolution used, so what a child searches and what the pre-flight report says
/// was searched cannot disagree. Passing the raw value instead would reinstate one level down the
/// substitution the resolution filter refused one level up: a `cc1` or an `as` planted in a
/// world-writable directory would be executed by a driver this suite had vetted, while every artefact
/// still named the vetted driver. That module documents the reasoning in full, including why an empty
/// result leaves `PATH` unset rather than empty.
///
/// Nothing else is inherited, so there is no whitelist of inherited names to keep in step with this
/// comment — the absence of such a list is the invariant.
const CHILD_SEARCH_PATH_VARIABLE: &str = "PATH";

/// The environment every child of this suite is given, alongside a computed
/// [`CHILD_SEARCH_PATH_VARIABLE`] and the four names in [`CHILD_PRIVATE_DIRECTORY_VARIABLES`].
///
/// Fixed rather than inherited — nothing at all is inherited, which is the invariant recorded on
/// [`CHILD_SEARCH_PATH_VARIABLE`] — and chosen so that output is byte-reproducible: the C locale
/// makes number and message formatting invariant, `TZ=UTC` removes any dependence on the host's
/// time zone, and `TERM=dumb` stops a tool deciding to emit colour escapes into a stream this
/// suite compares byte for byte.
const FIXED_CHILD_VARIABLES: &[(&str, &str)] = &[
    ("LANG", "C"),
    ("LC_ALL", "C"),
    ("LANGUAGE", "C"),
    ("TZ", "UTC"),
    ("TERM", "dumb"),
];

/// The sanitizer-runtime settings forced on every child, so that no inherited value can weaken a
/// diagnostic.
///
/// Only the undefined-behaviour audit gate builds an instrumented artefact, but the settings are
/// applied to every child unconditionally: a variable that cannot reach *any* child cannot reach
/// the one that matters, and one rule with no exceptions is easier to verify than a rule with
/// one.
///
/// Each value is the strictest available: a diagnostic terminates the process rather than being
/// recovered from, and it is printed rather than suppressed. That is exactly the posture the
/// audit gate documents, expressed as configuration the environment cannot override.
const FORCED_SANITIZER_VARIABLES: &[(&str, &str)] = &[
    (
        "ASAN_OPTIONS",
        "abort_on_error=1:halt_on_error=1:detect_leaks=1:print_summary=1:exitcode=1",
    ),
    (
        "UBSAN_OPTIONS",
        "halt_on_error=1:print_stacktrace=1:silence_unsigned_overflow=0",
    ),
    ("LSAN_OPTIONS", "exitcode=1"),
    ("MSAN_OPTIONS", "halt_on_error=1:exitcode=1"),
    ("TSAN_OPTIONS", "halt_on_error=1:exitcode=1"),
];

/// Give `command` the suite's fixed environment, and nothing else.
///
/// Three groups, and nothing outside them: the computed search path from
/// [`env::sanitized_search_path`], the fixed names and values from [`child_fixed_environment`], and
/// `private_directory` installed under each of [`CHILD_PRIVATE_DIRECTORY_VARIABLES`].
///
/// Called by every spawn site in this suite without exception. A site that forgot it would
/// silently reinstate the whole inherited environment, which is why there is no variant that
/// takes an opt-out.
///
/// The set is enumerated by the two items above rather than written out here, because a finding's
/// reproduction script has to install the *same* environment for its own invocations. One
/// enumeration consumed twice cannot drift; two copies would, and the copy that drifted would be
/// the one a reader on another machine actually ran.
pub fn isolate_child_environment(command: &mut Command, private_directory: &Path) {
    command.env_clear();
    // Set from the vetted entries rather than inherited. `None` leaves it unset, which is the
    // fail-closed outcome documented on `env::sanitized_search_path`: on a machine whose whole search
    // path is writable by anyone there is no honest oracle, and a driver that cannot find `cc1` states
    // that far better than one that silently runs whatever was planted.
    if let Some(path) = env::sanitized_search_path() {
        command.env(CHILD_SEARCH_PATH_VARIABLE, path);
    }
    for (name, value) in child_fixed_environment() {
        command.env(name, value);
    }
    for name in CHILD_PRIVATE_DIRECTORY_VARIABLES {
        command.env(name, private_directory);
    }
}

/// The variables pointed at the cell's own workspace, so a child writes its scratch state there.
///
/// A tool that writes a cache, a history file or a temporary file puts it inside the cell's workspace
/// rather than into the invoking user's home directory or a shared temporary directory. That is what
/// makes the hermeticity claim true of the *children* as well as of the harness. All four names are
/// set because the three temporary-directory spellings are consulted by different tools and a tool
/// that reads only the one this suite left unset would fall back to the shared directory.
///
/// Public because a finding's reproduction script has to set the same four, pointed at the reader's
/// own scratch directory. Two lists would be two things to keep in step; this is one.
pub const CHILD_PRIVATE_DIRECTORY_VARIABLES: &[&str] = &["HOME", "TMPDIR", "TMP", "TEMP"];

/// Every fixed name and value a child of this suite receives, in the order they are applied.
///
/// The single enumeration of that set. [`isolate_child_environment`] installs it on a [`Command`],
/// and a finding's reproduction script writes it into the shell function through which it runs every
/// invocation, so a reproduction is performed under the environment the run used rather than under
/// whatever the reader happens to have exported. Deriving both from one function is what makes that
/// claim structurally true instead of a comment asserting it: a variable added to either table
/// appears in both places, and one added to the script alone cannot exist.
///
/// Excluded deliberately, because neither is fixed: `PATH`, which is computed by
/// [`env::sanitized_search_path`], and the four names in [`CHILD_PRIVATE_DIRECTORY_VARIABLES`], whose
/// value is the cell's own workspace and therefore differs per cell and per machine.
pub fn child_fixed_environment() -> Vec<(&'static str, &'static str)> {
    FIXED_CHILD_VARIABLES
        .iter()
        .chain(FORCED_SANITIZER_VARIABLES.iter())
        .copied()
        .collect()
}

/// Substrings that mark an environment variable as likely to hold a credential.
///
/// Matched case-insensitively against the variable's **name**, because a name is the only thing
/// available before a value is read and because continuous-integration systems name their secrets
/// conventionally. The list is deliberately broad: a false positive costs one redacted line in a
/// report, whereas a false negative commits a credential to the repository inside a finding's
/// environment fingerprint.
const SECRET_NAME_MARKERS: &[&str] = &[
    "SECRET",
    "TOKEN",
    "PASSWORD",
    "PASSWD",
    "CREDENTIAL",
    "PRIVATE_KEY",
    "APIKEY",
    "API_KEY",
    "ACCESS_KEY",
    "SESSION",
    "COOKIE",
    "AUTH",
    "SIGNATURE",
    "LICENSE_KEY",
    "NPM_",
    "CARGO_REGISTRY_TOKEN",
];

/// What a redacted value is replaced by, spelled once so a reader can search for it.
pub const REDACTED_PLACEHOLDER: &str = "[redacted]";

/// Shortest value that is replaced wherever it appears, rather than only in its named form.
///
/// The bare-occurrence rule in [`redact_secrets`] is a substring replacement, so it cannot tell a
/// credential from ordinary text that happens to spell the same characters. That is harmless for a
/// value of credential length and destructive below it: a session identifier of `1` — and
/// `XDG_SESSION_ID=1` is an entirely ordinary variable on a systemd host, whose name contains
/// `SESSION` — would rewrite the digit in every count, every digest and every triple in every
/// artifact the suite writes, replacing the whole of a report's evidence in order to hide one
/// character that is not secret in the first place.
///
/// Eight is chosen because nothing shorter is a credential worth protecting by substring match, and
/// because the two other defences still cover such a value completely: the `NAME=value` rule below
/// is applied at **every** length, which is the shape an environment listing actually renders, and
/// [`isolate_child_environment`] stops the value reaching a spawned tool at all, so there is no path
/// by which a child can echo it back.
const BARE_REDACTION_MIN_CHARS: usize = 8;

/// Every credential-bearing variable of this process, read once and ordered for repeatability.
///
/// Read once because [`redact_secrets`] is applied to every field of every report row, and because
/// a fresh read per field would make the result depend on when it was taken — two rows of one report
/// could then be redacted under two different rules. One snapshot gives the whole run one rule,
/// which is what the reporting module's determinism claim rests on.
///
/// Ordered by **descending value length**, then by name, because the replacements are applied in
/// sequence and [`std::env::vars`] yields no defined order. Where one secret's value is a prefix of
/// another's, replacing the shorter first would leave the tail of the longer one exposed —
/// `abc` redacted before `abcdef` yields `[redacted]def`. Longest-first cannot do that, and fixing
/// the order also makes the output a function of the environment rather than of iteration order.
fn secret_variables() -> &'static [(String, String)] {
    static SECRETS: OnceLock<Vec<(String, String)>> = OnceLock::new();
    SECRETS.get_or_init(|| {
        let mut found: Vec<(String, String)> = std::env::vars()
            .filter(|(name, value)| !value.is_empty() && secret_bearing_variable(name))
            .collect();
        found.sort_by(|left, right| {
            right
                .1
                .chars()
                .count()
                .cmp(&left.1.chars().count())
                .then_with(|| left.0.cmp(&right.0))
        });
        found
    })
}

/// True when a variable of this name is treated as holding a credential.
pub fn secret_bearing_variable(name: &str) -> bool {
    let upper = name.to_ascii_uppercase();
    SECRET_NAME_MARKERS
        .iter()
        .any(|marker| upper.contains(marker))
}

/// `raw` with the value of every credential-bearing environment variable removed.
///
/// The last line of defence for text that is about to be printed, written into a report or
/// committed inside a finding's environment fingerprint. [`isolate_child_environment`] already
/// stops a secret reaching a child at all; this closes the remaining path, where a tool the suite
/// spawned before isolation applied — or a tool that read a credential from a file — echoes one
/// back in its own output.
///
/// Two shapes are recognised, which between them cover how a value is actually rendered: the
/// `NAME=value` form an environment listing uses, and the bare occurrence of a value the suite
/// can still see in its own environment. The second is what catches a banner that prints a token
/// without naming it, and it is the one bounded by [`BARE_REDACTION_MIN_CHARS`] — for the reason
/// recorded there, which is that a substring rule shorter than that destroys evidence instead of
/// protecting it.
///
/// Cheap enough to sit on the hot path. The environment is read once by [`secret_variables`] and an
/// environment holding no credential-bearing variable — the ordinary case, and the case in this
/// suite's own sandbox — makes this an immediate return of the input, so applying it at every
/// reporting sink costs nothing when there is nothing to redact.
pub fn redact_secrets(raw: &str) -> String {
    let secrets = secret_variables();
    if secrets.is_empty() {
        return String::from(raw);
    }
    let mut text = String::from(raw);
    for (name, value) in secrets {
        // Checked before either replacement, because `String::replace` allocates a fresh string
        // whether or not it matched anything, and on the reporting path this runs for every field of
        // every row. The named form contains the value as a substring, so a value that is absent
        // rules both shapes out in one scan.
        if !text.contains(value.as_str()) {
            continue;
        }
        text = text.replace(
            &format!("{name}={value}"),
            &format!("{name}={REDACTED_PLACEHOLDER}"),
        );
        if value.chars().count() >= BARE_REDACTION_MIN_CHARS {
            text = text.replace(value.as_str(), REDACTED_PLACEHOLDER);
        }
    }
    text
}

// ---------------------------------------------------------------------------------------------
// Process-group supervision
//
// A compiler driver is a process tree: the driver spawns `cc1`, then `as`, then `ld`. An emulator
// runs a program that may itself fork. Terminating the process the suite holds a handle to is
// therefore not the same as terminating what it started, and the difference is not theoretical:
// a descendant that survives keeps the capture pipes open, so the harness's own reads never see
// end of file, and at the scale of the full matrix one leaked process per cell accumulates into
// thousands.
//
// The standard library can create a process group but cannot signal one, and signalling one
// without `libc` and without `unsafe` needs a program that can. `kill` is used for exactly that,
// with an argument vector and no shell, discovered and vetted like every other tool and with a
// documented fallback when it is absent. Measured: `kill -KILL -- -<pgid>` terminates a leader
// and both of its children, and `kill -0 -- -<pgid>` then exits non-zero, which is the
// verification signal.
// ---------------------------------------------------------------------------------------------

/// Put `command` in a process group of its own, so its whole tree can be terminated together.
///
/// The group identifier equals the child's own process identifier, which
/// [`std::process::Child::id`] reports, so no extra bookkeeping is needed to name the group
/// later.
///
/// A second, quieter benefit: a child in its own group no longer receives a signal sent to the
/// test runner's group, so a terminal interrupt aimed at `cargo test` cannot kill a compiler
/// mid-write and leave a half-produced artefact to be compared.
#[cfg(unix)]
pub fn own_process_group(command: &mut Command) {
    use std::os::unix::process::CommandExt;
    command.process_group(0);
}

/// Fallback for a platform with no process-group notion, where the request cannot be expressed.
#[cfg(not(unix))]
pub fn own_process_group(_command: &mut Command) {}

/// What terminating a process group established.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GroupTermination {
    /// The group was signalled and is now empty: every descendant is gone.
    Cleared,
    /// The group was signalled but a member was still present afterwards.
    ///
    /// Carries a sentence for the outcome's notes. Reported rather than retried without end,
    /// because a process that survives an uncatchable signal is not going to yield to a second
    /// one, and a report that says so is more useful than a run that hangs.
    Survivors(String),
    /// No tool able to signal a group was available, so only the immediate child was terminated.
    ///
    /// Carries a sentence for the outcome's notes, so a run in a reduced environment states the
    /// weaker guarantee rather than implying the stronger one.
    Unsupervised(String),
}

/// Signal `pgid`'s whole process group with an uncatchable kill and verify that it emptied.
///
/// `kill_tool` is the vetted `kill` executable, or `None` when none was discovered. The
/// verification step is what makes this more than a best effort: a group that still has a member
/// after the signal is reported, so a leaked descendant appears in the run's notes instead of
/// quietly holding a pipe open.
///
/// The signal is sent to the negated group identifier, which is the POSIX spelling for "every
/// process in this group". The `--` separator is passed so that the negative number is read as an
/// operand rather than as an option, whatever `kill` implementation is installed.
///
/// An existence check precedes the signal. The ordinary case — a child that started nothing, or
/// whose descendants all ended with it — is then settled by a single invocation, which matters
/// because this runs on every exit path of every one of the matrix's thousands of executions. It
/// also keeps the two failures apart: a `kill` that cannot run at all is a reduced environment,
/// while a `kill` that reports no such process is the postcondition this function exists to
/// establish.
///
/// One residual hazard is named rather than left implicit. Callers sweep *after* reaping the child
/// they launched, because sweeping before it would find that child itself still in the group and
/// report it as a survivor. Between the reap and the signal the group identifier is no longer held
/// by any process of ours, so in principle another process could become the leader of a group with
/// that number and be signalled instead. Closing that window would require a group handle the
/// standard library does not offer. It is left open because the alternative is worse — a
/// false survivor report on every execution — and because identifiers are allocated sequentially
/// across the whole process-identifier space, so reuse inside a window of microseconds would
/// require the allocator to wrap in that time.
pub fn terminate_process_group(pgid: u32, kill_tool: Option<&Path>) -> GroupTermination {
    let Some(tool) = kill_tool else {
        return GroupTermination::Unsupervised(String::from(
            "no `kill` utility was discovered, so only the immediate child was terminated; a \
             descendant it started may have survived, and this run therefore cannot claim that \
             every process it launched has ended. Installing procps or util-linux restores the \
             guarantee",
        ));
    };
    let group = format!("-{pgid}");
    // Asked before the signal rather than only after it, for two reasons. It is the cheapest
    // possible answer in the ordinary case — every well-behaved child leaves an empty group, so one
    // invocation settles it instead of two — and it separates "the utility cannot run here" from
    // "the group is already empty", which a kill of an empty group reports with the same non-zero
    // status as a kill that failed for any other reason.
    match signal_group(tool, "-0", &group) {
        None => return GroupTermination::Unsupervised(unswept_reason(tool)),
        // No member at all: there is nothing to signal, and the postcondition already holds.
        Some(false) => return GroupTermination::Cleared,
        Some(true) => {}
    }
    if signal_group(tool, "-KILL", &group).is_none() {
        return GroupTermination::Unsupervised(unswept_reason(tool));
    }
    match signal_group(tool, "-0", &group) {
        // Exit status zero from a bare existence check means at least one member is still there.
        Some(true) => GroupTermination::Survivors(format!(
            "process group {pgid} still had a member after an uncatchable kill, so a descendant of \
             this child outlived it; it may still hold the capture pipes open"
        )),
        _ => GroupTermination::Cleared,
    }
}

/// How long one `kill` invocation is given to finish before it is itself terminated.
///
/// Generous against any plausible honest duration — signalling a process group is a single system
/// call and the utility around it does nothing else — and short against the run it must not stall.
/// Up to three invocations are made per cleanup, so this is also a third of the worst case a single
/// cleanup can cost.
const GROUP_SIGNAL_DEADLINE: Duration = Duration::from_secs(5);

/// How often a `kill` invocation is polled while it is being waited for.
///
/// A poll rather than a blocking wait because the standard library offers no timed wait on a child,
/// and short enough that the ordinary case — a utility that has already finished — adds no
/// measurable delay to a cleanup that happens after every one of the suite's several thousand
/// invocations.
const GROUP_SIGNAL_POLL: Duration = Duration::from_millis(20);

/// Why a sweep did not happen, distinguishing a refusal from an ordinary failure to run.
///
/// Computed only on the path where the sweep already failed, so the ordinary case pays nothing for
/// it. The distinction is worth drawing because the two causes call for opposite responses: a utility
/// that could not be executed is a condition of the machine, whereas one that is no longer the file
/// that was resolved is a substitution, and reporting the second as the first is exactly the silence
/// the pre-spawn confirmation exists to remove.
fn unswept_reason(tool: &Path) -> String {
    match env::confirm_vetted_tool_unchanged(tool) {
        Some(change) => format!(
            "the `kill` utility is no longer the file that was resolved — {change} — so it was \
             not run; only the immediate child was terminated and a descendant may have survived. \
             Refusing is deliberate: handing a signal and a process-group identifier to a program \
             nothing vetted is worse than an unswept group, which this verdict states plainly"
        ),
        None => format!(
            "the `kill` utility at {} could not be run, so only the immediate child was terminated \
             and a descendant may have survived",
            shown_path(tool)
        ),
    }
}

/// Send one signal to one process group, reporting whether the utility itself succeeded.
///
/// `None` means the utility could not be run, could not be waited for, **or was refused because it
/// is no longer the file that was resolved** — each a different fact from the group being absent,
/// which is why the return type is not a bare boolean. [`unswept_reason`] tells the last of the three
/// apart from the other two when the caller reports it.
///
/// # Why the wait is bounded
///
/// This runs on the cleanup path, and the cleanup path is what a per-cell timeout depends on: the
/// harness's watchdog fires, terminates the child, and then sweeps the child's process group so a
/// descendant cannot outlive it holding a capture pipe. An unbounded wait here therefore turns the
/// one mechanism that bounds a hung compiler into a hang of its own — and there is no outer bound
/// left to catch it, because this *is* the outer bound. That is a worse failure than the one being
/// cleaned up: a hung cell is reported as a timeout, whereas a hung cleanup stops the whole run with
/// no verdict for anything.
///
/// The wait can genuinely fail to return. The utility is resolved from the machine, so it may be a
/// script or a wrapper rather than the expected binary; and a `kill` invocation contends for the
/// same process table as everything else on a loaded machine. Neither needs to be likely for the
/// bound to be worth having, because the cost of the bound is one polled loop and the cost of its
/// absence is the entire run.
///
/// On expiry the utility is itself killed and reaped, and the outcome is reported as "could not be
/// run". That is accurate: an invocation that did not complete has established nothing about the
/// group, and [`terminate_process_group`] turns it into an `Unsupervised` verdict, which states that
/// a descendant may have survived rather than claiming a sweep that did not happen. The reap is
/// bounded too, so a child that cannot be reaped leaves one zombie rather than a stalled run.
fn signal_group(tool: &Path, signal: &str, group: &str) -> Option<bool> {
    let mut command = Command::new(tool);
    command.arg(signal).arg("--").arg(group);
    command
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null());
    isolate_child_environment(&mut command, &build_root());
    // The last statement before the launch. This utility is handed a signal and a process-group
    // identifier, so a substitution after it was resolved would hand both to a program nothing
    // vetted. Refusing produces `None`, which [`terminate_process_group`] reports as an honest
    // `Unsupervised` verdict rather than a claimed sweep, and [`unswept_reason`] then names the
    // substitution rather than filing it under the generic "could not be run".
    if env::confirm_vetted_tool_unchanged(tool).is_some() {
        return None;
    }
    let mut child = command.spawn().ok()?;
    let started = Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(status)) => return Some(status.success()),
            // Still running. Fall through to the deadline test rather than sleeping first, so a
            // utility that has already exited by the time of the second poll is not made to wait.
            Ok(None) => {}
            // The child can no longer be waited for at all, so no answer about the group is
            // obtainable from it.
            Err(_) => return None,
        }
        if started.elapsed() >= GROUP_SIGNAL_DEADLINE {
            let _ = child.kill();
            // Reaped rather than abandoned, so a cleanup that had to terminate its own helper does
            // not accumulate a zombie for every cell it ran on. Bounded for the same reason the wait
            // above is: this is the outermost bound in the suite, and nothing would catch it.
            let killed_at = Instant::now();
            while killed_at.elapsed() < GROUP_SIGNAL_DEADLINE {
                match child.try_wait() {
                    Ok(Some(_)) | Err(_) => break,
                    Ok(None) => thread::sleep(GROUP_SIGNAL_POLL),
                }
            }
            return None;
        }
        thread::sleep(GROUP_SIGNAL_POLL);
    }
}

// ---------------------------------------------------------------------------------------------
// Run identity
//
// Artefact paths in this suite are deterministic, and that is deliberate: a report row must lead
// a maintainer straight to a directory. Determinism across *processes*, however, means two
// concurrent invocations — two `cargo test` runs, or one run and a stale one — address the same
// files, and the second can purge or overwrite what the first is still producing. Worse, an area
// report left behind by an earlier run parses perfectly, so a summary can aggregate its rows and
// report a pass over a matrix this run never executed.
//
// The answer is not to randomize the paths, which would destroy the property the determinism was
// for. It is to give the run an identity, stamp it into every persisted row, and refuse a row
// that carries a different one. A stale or foreign artefact is then visible rather than
// authoritative.
// ---------------------------------------------------------------------------------------------

/// The identity of this run, stable for the whole process and different between processes.
///
/// Built from the process identifier and the process's start time, both of which every
/// concurrently executing run has a different value for, and rendered as lower-case hexadecimal
/// so it is safe in a path component, in a tab-separated field and in a Markdown table cell
/// without any escaping.
///
/// Memoized, so every feature-area test — which `cargo test` runs concurrently in one process —
/// sees the same value and their rows aggregate together. A second `cargo test` process gets a
/// different value, and its rows are refused by this run's summary rather than counted in it.
pub fn run_id() -> &'static str {
    static RUN_ID: OnceLock<String> = OnceLock::new();
    RUN_ID.get_or_init(|| {
        let started = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|since| since.as_nanos())
            .unwrap_or_default();
        format!("{:08x}{:016x}", std::process::id(), started)
    })
}

/// A stable 64-bit digest of a list of text components, rendered as hexadecimal.
///
/// FNV-1a, chosen for the same reason `findings.rs` chose it: it is a fixed specification, so it
/// produces the same value in every process, on every machine and under every toolchain version.
/// The standard library's default hasher is documented as unstable across releases and would make
/// a digest written by one run unrecognisable to the next.
///
/// Not a cryptographic digest and not used as one. Its job is to detect a *mismatch* — an area
/// report produced under a different matrix, a different tool set or a different corpus — where
/// the components being compared are themselves recorded alongside it in the same artefact.
///
/// The arithmetic itself lives in [`fnv1a64`] and the rendering in [`digest_hex`], and this
/// delegates to them rather than repeating either. Two copies of a hash are two chances for one of
/// them to be adjusted, and a digest that differs by call site is worse than no digest: it reports
/// a mismatch between two artefacts that describe the same thing.
pub fn stable_digest(components: &[&str]) -> String {
    digest_hex(components)
}
