//! Shared vocabulary, flag tables and path roots for the differential conformance
//! harness driven by `tests/conformance.rs`.
//!
//! # The three oracles
//!
//! Each cell of the build matrix — one program, one target, one optimization level — is
//! judged on stdout bytes and exit status alone:
//!
//! - [`Oracle::ReferenceCompiler`] compares bcc against an external reference C compiler
//!   at the same target and level.
//! - [`Oracle::CrossBackend`] compares every non-baseline target against
//!   [`Target::BASELINE`] at the same level.
//! - [`Oracle::GoldenRecord`] compares a cell against the `expected_stdout` recorded in
//!   the program's own `.expected` file.
//!
//! Standard error is captured for finding artifacts but never compared, because
//! diagnostic wording legitimately differs between compilers.
//!
//! # Invariants callers may rely on
//!
//! - Only `std` is used; the project permits no third-party crate.
//! - This directory contains no `#[test]` function and no `main.rs`, so Cargo treats it
//!   as a plain module directory rather than a test target.
//! - The harness itself writes nothing outside the Cargo build directory. The three write
//!   roots are [`work_root`] (one workspace per cell, keyed by [`CellKey::slug`]),
//!   [`report_root`] (one file per feature area, plus the run summary) and
//!   [`findings_root`] (findings generated by the current run). The committed finding set
//!   under [`corpus_root`] is a deliverable and is never written by a run.
//! - No shared **paths**: a cell's workspace path is a pure function of its identity and each
//!   area writes only its own report file, so `cargo test`'s default concurrency needs no lock
//!   to keep two writers apart. The few facts that are genuinely process-wide — which areas
//!   have published, whether the run summary has been finalized, the retention prunings a
//!   sweep recorded, and the configuration fingerprint this run adopted — each sit behind one
//!   small mutex, and none of those guards is ever held across a file write.
//!
//! # What that write invariant does not claim
//!
//! It is a statement about **paths this harness constructs**, not an operating-system
//! sandbox. Nothing here isolates syscalls or the network, enters a namespace or a `chroot`, so a
//! program that opened a socket or an absolute path would succeed; the bounding utility and the
//! execution runners are executed from wherever they are installed; and a crash dump lands where
//! the host's `kernel.core_pattern` says, which no safe standard-library API lets this code change
//! between the fork and the exec. What keeps the *programs under test* off the network and out of
//! the wider filesystem is corpus-authoring policy — every program takes its whole input from
//! literals in its own source — rather than enforcement in this code. The module documentation of
//! `sandbox` states the full boundary in one place.
//!
//! What this harness *does* enforce about a child, at every spawn site without exception, is its
//! **environment**: [`isolate_child_environment`] clears it and installs only a computed search
//! path, a fixed set of locale, time-zone, terminal and sanitizer settings, and the cell's own
//! workspace under each of `HOME`, `TMPDIR`, `TMP` and `TEMP`. So a tool that writes a cache or a
//! scratch file where those variables point does write inside the build directory. A driver that
//! ignores them and hard-codes a path — `gcc -###` shows `/tmp/cc*` for the assembler input and the
//! linker response file — is unaffected, because a variable cannot bind a program that never reads
//! it. Environment isolation is therefore a real guarantee about what a child is *told* and not a
//! guarantee about where every child writes.
//!
//! Edition 2021, minimum supported Rust 1.70.

